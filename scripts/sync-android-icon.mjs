#!/usr/bin/env node
// scripts/sync-android-icon.mjs
//
// Makes the INSTALLED app icon follow the admin Branding page — at build time,
// so a new APK (and, where the script can write them, the PWA icons in the
// repo) carries whatever logo the admin has saved, with no code edit.
//
// Why a build step and not a runtime trick: Android's launcher icon is a
// resource inside the APK. It cannot be swapped remotely — a new APK must be
// built. This script is what the GitHub Actions Android build runs first, so
// the icon baked into that APK is the live one. It never runs on a normal
// web/Vercel deploy (Vercel's build has no service-account credentials), and
// it never fails a build: without credentials, without a custom logo, or with
// an unreachable file it logs why and leaves the committed icons untouched.
//
// What it writes (only when the bytes actually change):
//   · android/app/src/main/res/mipmap-*/ic_launcher{,_round,_foreground}.png
//   · public/icons/*            (PWA icons, from the same pipeline)
//   · resources/icon.png        (Capacitor's master for future `cap` runs)
//   · public/branding/logo-source.png (the pipeline's master)
//
// Every icon is generated by scripts/generate-icons.cjs, so the mask-safe
// geometry (and tests/appIconSafeZone.test.mjs) applies to a brand-new logo
// exactly as it does to the shipped one.
//
// Environment:
//   FIREBASE_SERVICE_ACCOUNT=…  (or FIREBASE_PROJECT_ID + FIREBASE_CLIENT_EMAIL
//                                + FIREBASE_PRIVATE_KEY)  → read settings/branding
//   BRANDING_LOGO_URL=…         → skip Firestore and use this URL directly
//   GITHUB_STEP_SUMMARY         → set by Actions; a summary row is appended
//
// Run:  node scripts/sync-android-icon.mjs

import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const icons = require("./generate-icons.cjs");

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const ANDROID_RES = path.join(ROOT, "android", "app", "src", "main", "res");
const ANDROID_ROUND_ICON = path.join(ANDROID_RES, "mipmap-anydpi-v26", "ic_launcher_round.xml");
const MASTER = path.join(ROOT, "public", "branding", "logo-source.png");
const RESOURCES_ICON = path.join(ROOT, "resources", "icon.png");
const MENU_STAMP = path.join(ANDROID_RES, "values", "brand_icon.xml");

const log = (message) => console.log(`[brand-icon] ${message}`);

/** Written to the Actions run summary so the build log says what happened. */
function summarise(line) {
  const summary = process.env.GITHUB_STEP_SUMMARY;
  if (!summary) return;
  try {
    fs.appendFileSync(summary, `${line}\n`);
  } catch {
    /* the summary is a nicety, never a build failure */
  }
}

function skip(reason) {
  log(`skipped — ${reason}`);
  summarise(`- App icon sync: **skipped** (${reason})`);
  process.exit(0);
}

/** settings/branding.logoUrl through the Admin SDK. Null when not configured. */
async function logoUrlFromFirestore() {
  const hasServiceAccount = Boolean(String(process.env.FIREBASE_SERVICE_ACCOUNT || "").trim());
  const hasSplitCredentials =
    Boolean(String(process.env.FIREBASE_CLIENT_EMAIL || "").trim()) &&
    Boolean(String(process.env.FIREBASE_PRIVATE_KEY || "").trim());
  if (!hasServiceAccount && !hasSplitCredentials && !process.env.BRANDING_LOGO_URL) return null;

  const { initializeApp, cert, applicationDefault } = require("firebase-admin/app");
  const { getFirestore } = require("firebase-admin/firestore");

  let credential = null;
  if (hasServiceAccount) {
    const raw = String(process.env.FIREBASE_SERVICE_ACCOUNT).trim();
    const text = raw.startsWith("{") ? raw : Buffer.from(raw, "base64").toString("utf8");
    const parsed = JSON.parse(text);
    credential = cert({
      projectId: parsed.project_id || parsed.projectId,
      clientEmail: parsed.client_email || parsed.clientEmail,
      privateKey: String(parsed.private_key || parsed.privateKey || "").replace(/\\n/g, "\n"),
    });
  } else if (hasSplitCredentials) {
    credential = cert({
      projectId: String(process.env.FIREBASE_PROJECT_ID || "my-website-761e9"),
      clientEmail: String(process.env.FIREBASE_CLIENT_EMAIL).trim(),
      privateKey: String(process.env.FIREBASE_PRIVATE_KEY).replace(/\\n/g, "\n"),
    });
  }

  const app = initializeApp({
    credential: credential || applicationDefault(),
    projectId: process.env.FIREBASE_PROJECT_ID || "my-website-761e9",
  });
  const snap = await getFirestore(app).collection("settings").doc("branding").get();
  const raw = snap.exists ? snap.data()?.logoUrl : "";
  return typeof raw === "string" && /^https?:\/\//i.test(raw.trim()) ? raw.trim() : null;
}

async function download(url) {
  const res = await fetch(url, { redirect: "follow", headers: { Accept: "image/*" } });
  if (!res.ok) throw new Error(`HTTP ${res.status}`);
  const type = String(res.headers.get("content-type") || "").toLowerCase();
  if (!type.startsWith("image/") && type !== "application/octet-stream") {
    throw new Error(`unexpected content-type "${type || "none"}"`);
  }
  const buffer = Buffer.from(await res.arrayBuffer());
  if (buffer.byteLength < 64) throw new Error("file is empty");
  if (buffer.byteLength > 12 * 1024 * 1024) throw new Error("file is larger than 12 MB");
  return buffer;
}

async function writeIfChanged(file, bytes) {
  const current = fs.existsSync(file) ? fs.readFileSync(file) : null;
  if (current && current.equals(bytes)) return false;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, bytes);
  log(`updated ${path.relative(ROOT, file)}`);
  return true;
}

async function main() {
  const explicit = String(process.env.BRANDING_LOGO_URL || "").trim() || null;
  let url = explicit;
  if (!url) {
    try {
      url = await logoUrlFromFirestore();
    } catch (error) {
      skip(`could not read settings/branding (${error instanceof Error ? error.message : error})`);
    }
  }
  if (!url) skip("no custom logo saved in Branding (using the committed brand assets)");

  let bytes;
  try {
    bytes = await download(url);
  } catch (error) {
    skip(`could not download ${url} (${error instanceof Error ? error.message : error})`);
  }

  const sharp = require("sharp");
  let normalised;
  try {
    normalised = await sharp(bytes).png().toBuffer();
    await sharp(normalised).metadata();
  } catch (error) {
    skip(`the downloaded file is not a raster image sharp can read (${error instanceof Error ? error.message : error})`);
  }

  const { glyph, bounds, luminance } = await icons.readGlyph(normalised);
  // A light (near-white) logo must NOT be composited on the white plate — that
  // is a blank launcher icon. Same rule the dev generator uses.
  const plate = icons.plateFor(luminance);
  log(
    `logo ${bounds.width}×${bounds.height} px glyph measured from ${url} ` +
      `(luminance ${luminance.toFixed(0)} → ${plate === icons.DARK_PLATE ? "dark" : "white"} plate)`,
  );
  if (bounds.width < 64 || bounds.height < 64) {
    skip("the saved logo is too small (under 64 px) to build a launcher icon from");
  }

  const changed = [];
  if (await writeIfChanged(MASTER, normalised)) changed.push(path.relative(ROOT, MASTER));
  if (await writeIfChanged(RESOURCES_ICON, normalised)) changed.push(path.relative(ROOT, RESOURCES_ICON));

  for (const target of icons.targets()) {
    const built = await icons.build(glyph, target, plate);
    if (await writeIfChanged(target.file, built)) changed.push(path.relative(ROOT, target.file));
  }

  // Keep the resources the build reads in a known-good state: the adaptive
  // round icon must exist (a missing file would fail `gradlew assembleRelease`)
  // and the menu stamp gives the build log a human-readable version marker.
  if (!fs.existsSync(ANDROID_ROUND_ICON)) {
    fs.writeFileSync(
      ANDROID_ROUND_ICON,
      '<?xml version="1.0" encoding="utf-8"?>\n<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n    <background android:drawable="@color/ic_launcher_background" />\n    <foreground android:drawable="@mipmap/ic_launcher_foreground" />\n</adaptive-icon>\n',
    );
    changed.push(path.relative(ROOT, ANDROID_ROUND_ICON));
  }
  // A tiny, greppable record of WHICH logo this build baked in: the source
  // host plus a hash of the bytes. Deliberately not the full URL (a signed
  // Cloudinary URL is hundreds of characters and would bloat the resources).
  let host = "unknown";
  try {
    host = new URL(url).host.slice(0, 80);
  } catch {
    host = "inline";
  }
  const digest = crypto.createHash("sha256").update(normalised).digest("hex").slice(0, 12);
  const escapeXml = (value) => value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  const stamp = `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/sync-android-icon.mjs — the installed app icon follows the admin Branding logo. -->\n<resources>\n    <string name="brand_icon_source_host" translatable="false">${escapeXml(host)}</string>\n    <string name="brand_icon_source_sha256" translatable="false">${digest}</string>\n</resources>\n`;
  if (await writeIfChanged(MENU_STAMP, Buffer.from(stamp, "utf8"))) changed.push(path.relative(ROOT, MENU_STAMP));

  if (!changed.length) {
    log("every icon already matches the live branding — nothing to write");
    summarise("- App icon sync: **already up to date**");
    return;
  }
  log(`${changed.length} file(s) updated from the live branding`);
  summarise(`- App icon sync: **${changed.length} file(s) updated** from \`${url}\``);
}

main().catch((error) => {
  // Never break a build over the icon: the committed assets are always valid.
  log(`failed softly — ${error instanceof Error ? error.message : error}`);
  summarise(`- App icon sync: **failed softly** (${error instanceof Error ? error.message : error})`);
  process.exit(0);
});
