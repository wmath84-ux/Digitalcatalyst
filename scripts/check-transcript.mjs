#!/usr/bin/env node
// scripts/check-transcript.mjs
//
// "Caption available hai lekin transcript generate nahi ho raha" — this script
// says exactly why, in seconds.
//
// It runs the SAME pipeline the deployed /api/youtube-transcript route runs
// (api/_lib/youtubeTranscript.ts), from YOUR machine, and prints what every
// layer answered:
//
//   · InnerTube, per client (ANDROID · WEB · TVHTML5_SIMPLY_EMBEDDED · IOS ·
//     MWEB · WEB_EMBEDDED_PLAYER)
//   · the caption download for the chosen track
//   · the public watch page
//   · YouTube's own transcript panel (get_transcript)
//   · the legacy timedtext list
//
// Then, with --api, it asks your DEPLOYED route for the same video. The two
// answers side by side tell you which of the two it is:
//
//   works here + fails on the server  → YouTube is blocking your server's IP
//                                       (a datacentre thing; the app's
//                                       browser-side second opinion is what
//                                       covers it)
//   fails here too                   → the video really has no captions, or
//                                       YouTube changed shape — the layer
//                                       notes below say which
//
// Run:
//   node --experimental-strip-types scripts/check-transcript.mjs ksTPzTWUb6o
//   node --experimental-strip-types scripts/check-transcript.mjs <id> --lang hi
//   node --experimental-strip-types scripts/check-transcript.mjs <id> --api https://eduvora.shop

import { fetchYouTubeTranscript, parseYouTubeVideoId } from "../api/_lib/youtubeTranscript.ts";

const args = process.argv.slice(2);
let apiOrigin = "";
let language = "";
const rest = [];
for (let index = 0; index < args.length; index += 1) {
  if (args[index] === "--api") {
    apiOrigin = String(args[index + 1] || "").replace(/\/+$/, "");
    index += 1;
    continue;
  }
  if (args[index] === "--lang") {
    language = String(args[index + 1] || "").trim().toLowerCase();
    index += 1;
    continue;
  }
  rest.push(args[index]);
}

const videoId = parseYouTubeVideoId(rest[0] || "");
const say = (text = "") => process.stdout.write(`${text}\n`);
const rule = () => say("─".repeat(72));

if (!videoId) {
  say("Usage: node --experimental-strip-types scripts/check-transcript.mjs <videoId|watchURL> [--lang hi] [--api https://your-site]");
  process.exit(2);
}

say(`Video    : ${videoId}`);
say(`Language : ${language || "(the video's best track)"}`);
say(`From     : this machine (${process.platform}, node ${process.version})`);
rule();

const printAttempts = (attempts) => {
  if (!Array.isArray(attempts) || !attempts.length) {
    say("  (no layer report)");
    return;
  }
  for (const attempt of attempts) {
    const bits = [attempt.source];
    if (attempt.answered === false) bits.push("no answer");
    if (typeof attempt.tracks === "number") bits.push(`${attempt.tracks} track(s)`);
    if (attempt.playability) bits.push(`playability=${attempt.playability}`);
    if (attempt.blocked) bits.push("BLOCKED by YouTube");
    if (attempt.note) bits.push(attempt.note);
    say(`  · ${bits.join(" — ")}`);
  }
};

let local = null;
let localError = null;
const startedAt = Date.now();
try {
  local = await fetchYouTubeTranscript(videoId, language || undefined, { diagnostics: true });
} catch (error) {
  localError = error;
}
const localMs = Date.now() - startedAt;

rule();
say("LOCAL RESULT (this machine's IP)");
rule();
if (local) {
  say(`✓ ${local.segments.length} transcript lines in ${localMs}ms`);
  say(`  language : ${local.languageLabel} (${local.language})${local.autoGenerated ? " — auto-generated" : ""}`);
  say(`  title    : ${local.title || "(not reported)"}`);
  say(`  strategy : ${local.strategy || "caption-track"}`);
  say(`  tracks   : ${local.tracks.map((track) => `${track.language}${track.autoGenerated ? "(asr)" : ""}`).join(", ") || "—"}`);
  say(`  first    : [${Math.round(local.segments[0]?.start || 0)}s] ${String(local.segments[0]?.text || "").slice(0, 90)}`);
  say("  layers   :");
  printAttempts(local.attempts);
} else {
  say(`✗ ${localError?.code || "unknown"} in ${localMs}ms`);
  say(`  message : ${localError?.message || "(none)"}`);
  say("  layers  :");
  printAttempts(localError?.reports);
}

/* ── The deployed route, for comparison ──────────────────────────────────── */
let deployed = null;
if (apiOrigin) {
  rule();
  say(`DEPLOYED ROUTE  GET ${apiOrigin}/api/youtube-transcript`);
  rule();
  const url = new URL(`${apiOrigin}/api/youtube-transcript`);
  url.searchParams.set("v", videoId);
  url.searchParams.set("diagnostics", "1");
  if (language) url.searchParams.set("lang", language);
  const at = Date.now();
  try {
    const response = await fetch(url.toString(), { headers: { accept: "application/json" } });
    const raw = await response.text();
    let body = null;
    try {
      body = raw ? JSON.parse(raw) : null;
    } catch {
      body = null;
    }
    const ms = Date.now() - at;
    if (response.ok && body?.ok) {
      deployed = { ok: true };
      say(`✓ ${body.segments?.length || 0} lines in ${ms}ms (strategy ${body.strategy || "caption-track"})`);
      say("  layers:");
      printAttempts(body.attempts);
    } else if (body && body.ok === false) {
      deployed = { ok: false, code: body.code };
      say(`✗ HTTP ${response.status} · ${body.code} in ${ms}ms`);
      say(`  ${body.error || ""}`);
      say("  layers:");
      printAttempts(body.attempts);
      if (/text\/html/i.test(String(response.headers.get("content-type") || ""))) {
        say("  ↳ That origin answered HTML — it is not hosting the API functions.");
      }
    } else {
      deployed = { ok: false, code: `http-${response.status}` };
      say(`✗ HTTP ${response.status} in ${ms}ms — ${raw.slice(0, 200)}`);
      say("  ↳ HTML/empty answer means this origin does not run the serverless functions.");
    }
  } catch (error) {
    deployed = { ok: false, code: "network" };
    say(`✗ network error: ${error?.message || error}`);
  }
}

/* ── The verdict ─────────────────────────────────────────────────────────── */
rule();
say("VERDICT");
rule();
if (local && deployed && !deployed.ok) {
  say("The transcript IS readable — from here, but not from your server.");
  say("YouTube is refusing your deployment's IP (a datacentre blocklist, not your code).");
  say("What the app does about it: the browser-side second opinion runs on the learner's own");
  say("connection (InnerTube → get_transcript → timedtext), which is why the tab still fills in.");
  say("If it does not fill in on the website, check the learner's console for CORS refusals —");
  say("the installed app (WebView) is usually more permissive than a desktop browser.");
} else if (local && deployed?.ok) {
  say("Everything works: this machine AND the deployed route both read the transcript.");
} else if (!local && deployed?.ok) {
  say("Interesting: the server can read it but this machine cannot — your local network is the");
  say("problem (VPN, proxy, or a residential IP YouTube is currently suspicious of).");
} else if (!local) {
  const code = localError?.code;
  if (code === "no_captions") {
    say("Every layer agreed: this video offers NO caption track — manual or auto-generated.");
    say("Open it on YouTube: if the CC button is missing there too, there is genuinely nothing to read.");
    say("(The app only says this when at least one COMPLETE YouTube answer, or two independent");
    say("layers, confirm the caption list is empty — a throttled answer is reported as a throttle.)");
  } else if (code === "too_many_requests") {
    say("YouTube is throttling this IP right now (bot check / 429). Wait a few minutes and re-run.");
    say("The app shows 'YouTube is limiting requests right now' and retries — including from the");
    say("learner's own browser, which usually is not on the blocklist.");
  } else if (code === "video_unavailable") {
    say("YouTube would not share this video's player data: private, age-restricted or region-locked.");
  } else {
    say(`No layer could read the video (${code}). The layer notes above say which one stopped where.`);
    say("Re-run in a minute: transient refusals are common, and a different network changes the answer.");
  }
}

process.exit(local || deployed?.ok ? 0 : 1);
