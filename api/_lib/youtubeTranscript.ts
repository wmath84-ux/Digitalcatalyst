async function readInnerTubeWithClient(
  videoId: string,
  client: InnerTubeClientConfig,
  deadline: Deadline,
): Promise<RawPlayer | null> {
  try {
    const body: Record<string, unknown> = {
      context: {
        client: {
          clientName: client.clientName,
          clientVersion: client.clientVersion,
          ...(client.extraContext || {}),
        },
      },
      videoId,
      contentCheckOk: true,
      racyCheckOk: true,
    };

    const response = await fetchWithDeadline(
      INNERTUBE_API_URL,
      {
        method: "POST",
        headers: {
          "content-type": "application/json",
          "user-agent": client.userAgent,
          "accept-language": "en-US,en;q=0.9",
          origin: "https://www.youtube.com",
          referer: `https://www.youtube.com/watch?v=${videoId}`,
          "x-youtube-client-name": client.clientName === "WEB" || client.clientName === "MWEB" ? "1" : client.clientName === "IOS" ? "5" : "3",
          "x-youtube-client-version": client.clientVersion,
        },
        body: JSON.stringify(body),
      },
      deadline,
    );
    if (response.status === 429) {
      throw new TranscriptError("too_many_requests", "YouTube is limiting transcript requests from this network. Please try again in a little while.");
    }
    if (!response.ok) return null;
    const json = (await response.json()) as unknown;
    const player = readPlayerResponse(json);
    return player;
  } catch (error) {
    if (error instanceof TranscriptError && error.code === "too_many_requests") throw error;
    if (error instanceof TranscriptError && error.code === "timeout") throw error;
    return null;
  }
}

async function readInnerTubeAllClients(videoId: string, deadline: Deadline): Promise<RawPlayer | null> {
  let lastPlayerWithoutTracks: RawPlayer | null = null;
  for (const client of INNERTUBE_CLIENTS) {
    if (remainingMs(deadline) < 500) break; // almost out of budget
    let player: RawPlayer | null = null;
    try {
      player = await readInnerTubeWithClient(videoId, client, deadline);
    } catch (error) {
      if (error instanceof TranscriptError && error.code === "too_many_requests") throw error;
      if (error instanceof TranscriptError && error.code === "timeout") {
        // If we timed out on first client, try next quickly before giving up
        if (client.name !== "ANDROID") continue;
        throw error;
      }
      continue;
    }
    if (!player) continue;
    // If this client says bot/login, remember it but try next client before failing
    if (!player.tracks.length && isBotOrLoginReason(player.reason)) {
      lastPlayerWithoutTracks = player;
      continue;
    }
    if (player.tracks.length) return player;
    // No tracks but not a bot reason — keep as fallback
    if (!lastPlayerWithoutTracks) lastPlayerWithoutTracks = player;
  }
  return lastPlayerWithoutTracks;
}

async function readWatchPage(videoId: string, deadline: Deadline): Promise<RawPlayer | null> {
  let response: Response;
  try {
    response = await fetchWithDeadline(
      `https://www.youtube.com/watch?v=${encodeURIComponent(videoId)}&hl=en&gl=US&bpctr=9999999999&has_verified=1`,
      { headers: PLAYER_HEADERS },
      deadline,
    );
  } catch (error) {
    if (error instanceof TranscriptError) throw error;
    return null;
  }
  if (response.status === 429) {
    throw new TranscriptError("too_many_requests", "YouTube is temporarily limiting transcript requests from this network. Please try again in a little while.");
  }
  if (!response.ok) return null;
  let html = "";
  try {
    html = await response.text();
  } catch {
    return null;
  }
  const lowerHtml = html.toLowerCase();
  if (
    /class="g-recaptcha"/.test(html) ||
    lowerHtml.includes("sign in to confirm you're not a bot") ||
    lowerHtml.includes("confirm you're not a bot") ||
    lowerHtml.includes("confirm you are not a bot") ||
    /detected unusual traffic/.test(lowerHtml)
  ) {
    throw new TranscriptError("too_many_requests", "YouTube is temporarily limiting transcript requests from this network. Please try again in a little while.");
  }
  const playerJson = parseInlineJson(html, "ytInitialPlayerResponse");
  if (!playerJson) return null;
  return readPlayerResponse(playerJson);
}

/**
 * Legacy timedtext list endpoint — sometimes works when InnerTube is blocked.
 * https://www.youtube.com/api/timedtext?type=list&v=VIDEOID
 */
async function readTimedTextList(videoId: string, deadline: Deadline): Promise<RawPlayer | null> {
  let response: Response;
  try {
    response = await fetchWithDeadline(
      `https://www.youtube.com/api/timedtext?type=list&v=${encodeURIComponent(videoId)}&hl=en`,
      {
        headers: {
          "user-agent": WEB_USER_AGENT,
          "accept-language": "en-US,en;q=0.9",
          accept: "text/xml,application/xml;q=0.9,*/*;q=0.8",
        },
      },
      deadline,
    );
  } catch (error) {
    if (error instanceof TranscriptError) throw error;
    return null;
  }
  if (response.status === 429) {
    throw new TranscriptError("too_many_requests", "YouTube is temporarily limiting transcript requests from this network. Please try again in a little while.");
  }
  if (!response.ok) return null;
  let xml = "";
  try {
    xml = await response.text();
  } catch {
    return null;
  }
  const lower = xml.toLowerCase();
  if (
    lower.includes("sign in to confirm you're not a bot") ||
    lower.includes("confirm you're not a bot") ||
    lower.includes("class=\"g-recaptcha\"")
  ) {
    throw new TranscriptError("too_many_requests", "YouTube is temporarily limiting transcript requests from this network. Please try again in a little while.");
  }
  // Parse <track lang_code="en" name="English" kind="asr" ...>
  const tracks: RawTrack[] = [];
  const seen = new Set<string>();
  const trackRegex = /<track[^>]+>/g;
  let match: RegExpExecArray | null;
  while ((match = trackRegex.exec(xml)) !== null) {
    const tag = match[0];
    const langMatch = tag.match(/lang_code="([^"]+)"/);
    const nameMatch = tag.match(/name="([^"]*)"/);
    const kindMatch = tag.match(/kind="([^"]*)"/);
    const lang = langMatch ? langMatch[1].trim().toLowerCase() : "";
    if (!lang) continue;
    const label = nameMatch ? decodeTranscriptEntities(nameMatch[1]).trim() : transcriptLanguageLabel(lang);
    const kind = kindMatch ? kindMatch[1].trim().toLowerCase() : "";
    const autoGenerated = kind === "asr";
    const key = `${lang}|${autoGenerated ? "asr" : "manual"}`;
    if (seen.has(key)) continue;
    seen.add(key);
    // Build a baseUrl that fetchCaptionCues can use — host-locked to youtube.com
    const baseUrl = `https://www.youtube.com/api/timedtext?lang=${encodeURIComponent(lang)}&v=${encodeURIComponent(videoId)}`;
    tracks.push({ baseUrl, language: lang, label: label || transcriptLanguageLabel(lang), autoGenerated });
  }
  if (!tracks.length) return null;
  return {
    tracks,
    title: "",
    playability: "OK",
    reason: "",
  };
}

/* ── Caption body parsing ───────────────────────────────────────────────── */

export type RawCue = { start: number; end: number; text: string };

export function decodeTranscriptEntities(text: string): string {
  const once = String(text || "")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&apos;/g, "'")
    .replace(/&nbsp;/g, " ")
    .replace(/&#x([0-9a-fA-F]+);/g, (_, hex: string) => String.fromCodePoint(parseInt(hex, 16)))
    .replace(/&#(\d+);/g, (_, dec: string) => String.fromCodePoint(parseInt(dec, 10)));
  // Auto captions are occasionally double-encoded (`&amp;#39;`).
  return once.includes("&amp;") ? decodeTranscriptEntities(once) : once;
}

function cleanCueText(text: string): string {
  return decodeTranscriptEntities(text)
    .replace(/<[^>]*>/g, " ")
    .replace(/\u200b/g, "")
    .replace(/\s+/g, " ")
    .replace(/^(?:>>\s*)+/, "")
    .trim();
}

/** JSON3: `{ events: [{ tStartMs, dDurationMs, segs: [{ utf8 }] }] }`. */
export function parseCaptionJson3(raw: string): RawCue[] {
  let data: unknown;
  try {
    data = JSON.parse(raw);
  } catch {
    return [];
  }
  const events = (data && typeof data === "object" ? (data as { events?: unknown }).events : null);
  if (!Array.isArray(events)) return [];
  const cues: RawCue[] = [];
  for (const event of events) {
    if (!event || typeof event !== "object") continue;
    const record = event as Record<string, unknown>;
    const segs = Array.isArray(record.segs) ? record.segs : [];
    const text = cleanCueText(
      segs
        .map((seg) => (seg && typeof seg === "object" ? String((seg as { utf8?: unknown }).utf8 || "") : ""))
        .join(""),
    );
    if (!text) continue;
    const start = Math.max(0, Number(record.tStartMs || 0) / 1000);
    const duration = Math.max(0, Number(record.dDurationMs || 0) / 1000);
    cues.push({ start, end: start + duration, text });
  }
  return cues;
}

/** XML (classic `<text start dur>` and srv3 `<p t d><s>`), entity-decoded. */
export function parseCaptionXml(raw: string): RawCue[] {
  const xml = String(raw || "");
  const cues: RawCue[] = [];
  // srv3: <p t="1234" d="5678"><s>word</s>…</p>
  const paragraph = /<p\s+t="(\d+)"(?:\s+d="(\d+)")?[^>]*>([\s\S]*?)<\/p>/g;
  let match: RegExpExecArray | null;
  while ((match = paragraph.exec(xml)) !== null) {
    const inner = match[3] || "";
    const words: string[] = [];
    const wordRegex = /<s[^>]*>([\s\S]*?)<\/s>/g;
    let wordMatch: RegExpExecArray | null;
    while ((wordMatch = wordRegex.exec(inner)) !== null) words.push(wordMatch[1]);
    const text = cleanCueText(words.length ? words.join("") : inner.replace(/<[^>]*>/g, ""));
    if (!text) continue;
    const start = Math.max(0, Number(match[1]) / 1000);
    const duration = Math.max(0, Number(match[2] || 0) / 1000);
    cues.push({ start, end: start + duration, text });
  }
  if (cues.length) return cues;
  // Classic: <text start="1.23" dur="4.5">hello</text>
  const classic = /<text\s+start="([^"]*)"(?:\s+dur="([^"]*)")?[^>]*>([\s\S]*?)<\/text>/g;
  while ((match = classic.exec(xml)) !== null) {
    const text = cleanCueText(match[3]);
    if (!text) continue;
    const start = Math.max(0, Number(match[1]) || 0);
    const duration = Math.max(0, Number(match[2]) || 0);
    cues.push({ start, end: start + duration, text });
  }
  return cues;
}

/**
 * Merge YouTube's caption bites into readable lines.
 *
 * A sentence ends at `.` / `!` / `?` / `।`; a 1.5 second silence is a new
 * thought; a line never runs past ~14 seconds or ~280 characters. Every merge
 * keeps the FIRST cue's start, so the page's timestamp is where the sentence
 * begins — which is what a learner expects when they tap it.
 */
export function groupTranscriptCues(cues: RawCue[]): TranscriptSegment[] {
  const segments: TranscriptSegment[] = [];
  let current: RawCue | null = null;
  const flush = () => {
    if (!current) return;
    const text = current.text.replace(/\s+/g, " ").trim();
    if (text) {
      segments.push({
        start: Math.round(current.start * 1000) / 1000,
        duration: Math.max(0, Math.round((current.end - current.start) * 1000) / 1000),
        text,
      });
    }
    current = null;
  };
  for (const cue of cues) {
    if (!cue.text) continue;
    if (!current) {
      current = { ...cue };
      continue;
    }
    const gap = cue.start - current.end;
    const sentenceEnded = /[.!?।]$/.test(current.text);
    const tooLong = cue.end - current.start > 14 || current.text.length + cue.text.length > 280;
    if (gap > 1.5 || (sentenceEnded && current.text.length >= 55) || tooLong) {
      flush();
      current = { ...cue };
      continue;
    }
    current.text = `${current.text} ${cue.text}`.replace(/\s+/g, " ").trim();
    current.end = Math.max(current.end, cue.end);
  }
  flush();
  return segments;
}

/* ── Track choice ───────────────────────────────────────────────────────── */

/**
 * Pick the track the page asked for; when there is no request, prefer a manual
 * English track, then any manual track, then auto-generated English, then the
 * first track YouTube listed (usually the video's own language).
 */
export function chooseCaptionTrack(tracks: RawTrack[], requested?: string): RawTrack | null {
  if (!tracks.length) return null;
  const lang = String(requested || "").trim().toLowerCase();
  if (lang) {
    const exact = tracks.find((track) => track.language === lang);
    if (exact) return exact;
    const prefix = tracks.find((track) => track.language.startsWith(`${lang}-`) || lang.startsWith(`${track.language}-`));
    if (prefix) return prefix;
  }
  const manual = tracks.filter((track) => !track.autoGenerated);
  const auto = tracks.filter((track) => track.autoGenerated);
  return (
    manual.find((track) => track.language === "en" || track.language.startsWith("en-"))
    || manual[0]
    || auto.find((track) => track.language === "en" || track.language.startsWith("en-"))
    || auto[0]
    || tracks[0]
  );
}

async function fetchCaptionCues(track: RawTrack, deadline: Deadline): Promise<RawCue[]> {
  const url = new URL(track.baseUrl.startsWith("//") ? `https:${track.baseUrl}` : track.baseUrl);
  if (!isAllowedCaptionUrl(url.toString())) {
    throw new TranscriptError("no_transcript", "YouTube returned an unexpected caption URL.");
  }
  const headers = {
    "user-agent": WEB_USER_AGENT,
    "accept-language": "en-US,en;q=0.9",
    referer: "https://www.youtube.com/",
  };
  // JSON3 first — cleaner timing than the XML shapes.
  const json3 = new URL(url);
  json3.searchParams.set("fmt", "json3");
  try {
    const response = await fetchWithDeadline(json3.toString(), { headers }, deadline);
    if (response.status === 429) {
      throw new TranscriptError("too_many_requests", "YouTube is temporarily limiting transcript requests from this network. Please try again in a little while.");
    }
    if (response.ok) {
      const body = await response.text();
      if (/not a bot|sign in to confirm|g-recaptcha|unusual traffic/i.test(body)) {
        throw new TranscriptError("too_many_requests", "YouTube is temporarily limiting transcript requests from this network. Please try again in a little while.");
      }
      if (body.trim().startsWith("{")) {
        const cues = parseCaptionJson3(body);
        if (cues.length) return cues;
      }
      // A host that ignores fmt=json3 sends XML here.
      const xmlCues = parseCaptionXml(body);
      if (xmlCues.length) return xmlCues;
    }
  } catch (error) {
    if (error instanceof TranscriptError && (error.code === "timeout" || error.code === "too_many_requests")) throw error;
  }
  // The plain track URL (classic XML/srv3) as the second chance.
  const response = await fetchWithDeadline(url.toString(), { headers }, deadline);
  if (response.status === 429) {
    throw new TranscriptError("too_many_requests", "YouTube is temporarily limiting transcript requests from this network. Please try again in a little while.");
  }
  if (!response.ok) {
    throw new TranscriptError("no_transcript", "YouTube did not return this caption track.");
  }
  const body = await response.text();
  if (/not a bot|sign in to confirm|g-recaptcha|unusual traffic/i.test(body)) {
    throw new TranscriptError("too_many_requests", "YouTube is temporarily limiting transcript requests from this network. Please try again in a little while.");
  }
  const xmlCues = parseCaptionXml(body);
  if (xmlCues.length) return xmlCues;
  throw new TranscriptError("no_transcript", "This caption track came back empty.");
}

/* ── In-process cache ───────────────────────────────────────────────────── */

type CacheEntry = { at: number; payload: TranscriptPayload };
const cache = new Map<string, CacheEntry>();

function readCache(key: string): TranscriptPayload | null {
  const entry = cache.get(key);
  if (!entry) return null;
  if (Date.now() - entry.at > CACHE_TTL_MS) {
    cache.delete(key);
    return null;
  }
  return entry.payload;
}

function writeCache(key: string, payload: TranscriptPayload) {
  cache.delete(key);
  cache.set(key, { at: Date.now(), payload });
  while (cache.size > CACHE_MAX_ENTRIES) {
    const oldest = cache.keys().next().value;
    if (oldest === undefined) break;
    cache.delete(oldest);
  }
}

/** Test hook — keeps the pure suite hermetic. */
export function clearTranscriptCache() {
  cache.clear();
}

/* ── The orchestration ──────────────────────────────────────────────────── */

export async function fetchYouTubeTranscript(videoIdInput: string, requestedLanguage?: string): Promise<TranscriptPayload> {
  const videoId = parseYouTubeVideoId(videoIdInput);
  if (!videoId) throw new TranscriptError("bad_video", "That is not a YouTube video id.");

  const requested = String(requestedLanguage || "").trim().toLowerCase();
  const cacheKey = `${videoId}|${requested || "auto"}`;
  const cached = readCache(cacheKey);
  if (cached) return cached;

  const deadline = createDeadline();
  let player: RawPlayer | null = null;

  // 1. Try all InnerTube clients — ANDROID first, then WEB, IOS, MWEB
  try {
    player = await readInnerTubeAllClients(videoId, deadline);
  } catch (error) {
    if (error instanceof TranscriptError) throw error;
    player = null;
  }

  // 2. InnerTube can answer with playable metadata but no caption list
  // (age / region / bot checks); the public watch page often still carries
  // the tracks, so it is always consulted when the first answer had none.
  if (!player || !player.tracks.length) {
    try {
      const page = await readWatchPage(videoId, deadline);
      if (page?.tracks.length) player = page;
      else if (!player) player = page;
    } catch (error) {
      // A bot-check on the watch page is a rate limit — don't hide it behind
      // the next fallback which would hit the same wall.
      if (error instanceof TranscriptError && error.code === "too_many_requests") {
        // But if we already have a player with tracks from InnerTube, keep it
        if (!player || !player.tracks.length) throw error;
      }
    }
  }

  // 3. Legacy timedtext list — sometimes works when both InnerTube and watch
  // page are gated. This is the final network attempt before giving up.
  if (!player || !player.tracks.length) {
    try {
      const timed = await readTimedTextList(videoId, deadline);
      if (timed?.tracks.length) player = timed;
      else if (!player) player = timed;
    } catch (error) {
      if (error instanceof TranscriptError && error.code === "too_many_requests") {
        if (!player || !player.tracks.length) throw error;
      }
    }
  }

  if (!player) {
    throw new TranscriptError("fetch_failed", "YouTube's player data could not be read. Please try again in a moment.");
  }
  if (!player.tracks.length) {
    const reason = player.reason || "";
    const status = player.playability.toUpperCase();

    // Bot / sign-in checks are ALWAYS rate limits with a friendly message —
    // never leak YouTube's raw "Sign in to confirm you're not a bot" string
    // to the learner, because the Transcript tab's copy is what they should see.
    if (isBotOrLoginReason(reason) || status === "LOGIN_REQUIRED") {
      throw new TranscriptError("too_many_requests", "YouTube is temporarily limiting transcript requests from this network. Please try again in a little while.");
    }
    if (status && status !== "OK") {
      throw new TranscriptError(
        "video_unavailable",
        "YouTube didn't share this video's player data. It may be private, age-restricted or region-locked.",
      );
    }
    throw new TranscriptError("no_captions", "This video has no captions (neither manual nor auto-generated), so there is no transcript to show.");
  }

  const chosen = chooseCaptionTrack(player.tracks, requested);
  if (!chosen) throw new TranscriptError("no_captions", "This video has no captions (neither manual nor auto-generated), so there is no transcript to show.");

  const cues = await fetchCaptionCues(chosen, deadline);
  if (!cues.length) throw new TranscriptError("no_transcript", "YouTube returned an empty caption track for this video. Try another video from the library.");

  const allSegments = groupTranscriptCues(cues);
  if (!allSegments.length) throw new TranscriptError("no_transcript", "YouTube returned an empty caption track for this video. Try another video from the library.");
  const truncated = allSegments.length > MAX_SEGMENTS;
  const segments = truncated ? allSegments.slice(0, MAX_SEGMENTS) : allSegments;

  const payload: TranscriptPayload = {
    videoId,
    title: player.title,
    language: chosen.language,
    languageLabel: chosen.label || transcriptLanguageLabel(chosen.language),
    autoGenerated: chosen.autoGenerated,
    tracks: player.tracks.map((track) => ({
      language: track.language,
      label: track.label || transcriptLanguageLabel(track.language),
      autoGenerated: track.autoGenerated,
    })),
    segments,
    truncated,
    fetchedAt: Date.now(),
  };
  writeCache(cacheKey, payload);
  return payload;
}

/* ── The serverless handler ─────────────────────────────────────────────── */

const first = (value: string | string[] | undefined): string =>
  Array.isArray(value) ? String(value[0] || "") : String(value || "");

const statusFor = (code: TranscriptErrorCode): number => {
  switch (code) {
    case "bad_video":
      return 400;
    case "video_unavailable":
    case "no_captions":
      return 404;
    case "no_transcript":
      return 422;
    case "too_many_requests":
      return 429;
    case "timeout":
      return 504;
    default:
      return 502;
  }
};

/**
 * `GET /api/youtube-transcript?v=<id>&lang=<code>`
 * Answers `{ ok: true, …TranscriptPayload }` or `{ ok: false, code, error }`.
 */
export async function handleYouTubeTranscript(
  req: TranscriptRequestLike,
  res: TranscriptResponseLike,
): Promise<void> {
  const method = String(req.method || "GET").toUpperCase();
  if (method !== "GET" && method !== "HEAD") {
    res.status(405).json({ ok: false, code: "method_not_allowed", error: "Use GET." });
    return;
  }
  const query = req.query || {};
  const rawId = first(query.v) || first(query.videoId) || first(query.url) || first(query.id);
  const videoId = parseYouTubeVideoId(rawId);
  if (!videoId) {
    res.status(400).json({
      ok: false,
      code: "bad_video",
      error: "Pass ?v=<11-character YouTube video id> (a watch URL also works).",
    });
    return;
  }
  const language = first(query.lang).trim().toLowerCase().slice(0, 35);
  try {
    const payload = await fetchYouTubeTranscript(videoId, language || undefined);
    res.setHeader("Cache-Control", "public, s-maxage=3600, stale-while-revalidate=86400");
    res.setHeader("Content-Type", "application/json; charset=utf-8");
    res.status(200).json({ ok: true, ...payload });
  } catch (error) {
    const transcriptError = error instanceof TranscriptError
      ? error
      : new TranscriptError("fetch_failed", error instanceof Error ? error.message : "The transcript could not be fetched.");
    res.setHeader("Cache-Control", "no-store");
    res.setHeader("Content-Type", "application/json; charset=utf-8");
    res.status(statusFor(transcriptError.code)).json({
      ok: false,
      code: transcriptError.code,
      error: transcriptError.message,
      videoId,
    });
  }
}
