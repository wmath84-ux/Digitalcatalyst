/**
 * `params` for get_transcript: protobuf field 1 (wire type 2) + length + the
 * video id. YouTube's own web client sends exactly this to open the panel.
 */
export function buildTranscriptParams(videoId: string): string {
  const id = String(videoId || "").trim();
  if (!VIDEO_ID.test(id)) return "";
  const bytes = [0x0a, id.length];
  for (let index = 0; index < id.length; index += 1) bytes.push(id.charCodeAt(index) & 0xff);
  // Runtime-agnostic base64 (no Buffer here: vite.config.ts imports this file
  // into the dev server, and the same helper is worth keeping portable).
  const ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
  let out = "";
  for (let index = 0; index < bytes.length; index += 3) {
    const chunk = [bytes[index], bytes[index + 1], bytes[index + 2]];
    const have = chunk.filter((value) => value !== undefined).length;
    const value = ((chunk[0] || 0) << 16) | ((chunk[1] || 0) << 8) | (chunk[2] || 0);
    out += ALPHABET[(value >> 18) & 63] + ALPHABET[(value >> 12) & 63];
    out += have > 1 ? ALPHABET[(value >> 6) & 63] : "=";
    out += have > 2 ? ALPHABET[value & 63] : "=";
  }
  return out;
}

/**
 * A total request budget that fits the deployed function's window.
 *
 * `vercel.json` gives `api/referral-leaderboard.ts` (which serves this route)
 * `maxDuration: 60`, so the old 14 s budget was self-imposed and far too
 * tight: four InnerTube clients at 5 s each could burn it before the watch
 * page was even tried — and a request that dies on the clock answers
 * `timeout`, which the page renders as a dead end. The clients now run in
 * parallel waves, and the budget is spent on actual attempts.
 */
const REQUEST_BUDGET_MS = 26_000;
const SINGLE_FETCH_MS = 9_000;
/** The course player shows the first N lines immediately; 4,000 is ~10 hours. */
const MAX_SEGMENTS = 4_000;
/** Long videos stay useful in memory (and under the CDN's object size). */
const CACHE_TTL_MS = 30 * 60 * 1000;
const CACHE_MAX_ENTRIES = 60;

const VIDEO_ID = /^[A-Za-z0-9_-]{11}$/;
const CAPTION_HOST = /(^|\.)youtube(-nocookie)?\.com$/i;

/* ── Public input parsing ───────────────────────────────────────────────── */

/**
 * Accepts an id, a watch URL, a youtu.be link, an embed URL or a shorts link
 * and answers the 11-character id — or "" when there is none.
 *
 * The Course Player only ever sends the id from `extractYouTubeId`, but the
 * server route is public, so it must not assume a well-behaved client.
 */
export function parseYouTubeVideoId(input: unknown): string {
  const raw = String(input || "").trim();
  if (!raw) return "";
  if (VIDEO_ID.test(raw)) return raw;
  let url: URL | null = null;
  try {
    url = new URL(raw.startsWith("//") ? `https:${raw}` : raw);
  } catch {
    url = null;
  }
  if (url) {
    const host = url.hostname.toLowerCase().replace(/^www\./, "");
    if (host === "youtu.be") {
      const candidate = url.pathname.split("/").filter(Boolean)[0] || "";
      return VIDEO_ID.test(candidate) ? candidate : "";
    }
    if (host === "youtube.com" || host === "m.youtube.com" || host === "youtube-nocookie.com") {
      const queryId = url.searchParams.get("v") || "";
      if (VIDEO_ID.test(queryId)) return queryId;
      const parts = url.pathname.split("/").filter(Boolean);
      const marker = parts.findIndex((part) => ["embed", "shorts", "live", "v", "e"].includes(part));
      const candidate = marker >= 0 ? parts[marker + 1] || "" : "";
      if (VIDEO_ID.test(candidate)) return candidate;
    }
    // A URL that parsed but is not a YouTube host is never a video id,
    // even when it carries a `v=` parameter.
    return "";
  }
  // Last resort for a pasted fragment (not a URL at all).
  const match = raw.match(/(?:v=|youtu\.be\/|embed\/|shorts\/|live\/)([A-Za-z0-9_-]{11})/);
  return match ? match[1] : "";
}

/** "en-US" → "English"; unknown codes keep the code itself. */
export function transcriptLanguageLabel(code: string): string {
  const clean = String(code || "").trim();
  if (!clean) return "Unknown";
  try {
    const names = new Intl.DisplayNames(["en"], { type: "language" });
    const label = names.of(clean) || names.of(clean.split("-")[0]) || "";
    if (label) return label;
  } catch {
    /* very old runtime without Intl.DisplayNames — fall through */
  }
  const base = clean.split("-")[0];
  const fallback: Record<string, string> = {
    en: "English", hi: "Hindi", ur: "Urdu", es: "Spanish", fr: "French",
    de: "German", pt: "Portuguese", ar: "Arabic", zh: "Chinese", ja: "Japanese",
    ko: "Korean", ru: "Russian", bn: "Bengali", ta: "Tamil", te: "Telugu",
    mr: "Marathi", gu: "Gujarati", kn: "Kannada", ml: "Malayalam", pa: "Punjabi",
    id: "Indonesian", tr: "Turkish", vi: "Vietnamese", th: "Thai", it: "Italian",
  };
  return fallback[base] || clean;
}

/* ── HTML / JSON extraction ─────────────────────────────────────────────── */

/**
 * Read the JSON object assigned to `var ytInitialPlayerResponse = {…};` using a
 * balanced-brace scan. A greedy regex breaks on the first `}` inside a string,
 * which is exactly how the older scrapers lost captions on some videos.
 */
export function parseInlineJson(html: string, globalName: string): Record<string, unknown> | null {
  const text = String(html || "");
  const markers = [`var ${globalName} = `, `var ${globalName}=`, `${globalName} = `, `${globalName}=`];
  for (const marker of markers) {
    const at = text.indexOf(marker);
    if (at === -1) continue;
    const start = text.indexOf("{", at + marker.length);
    if (start === -1) continue;
    let depth = 0;
    let inString = false;
    let escaped = false;
    for (let index = start; index < text.length; index += 1) {
      const char = text[index];
      if (inString) {
        if (escaped) escaped = false;
        else if (char === "\\") escaped = true;
        else if (char === '"') inString = false;
        continue;
      }
      if (char === '"') {
        inString = true;
        continue;
      }
      if (char === "{") depth += 1;
      else if (char === "}") {
        depth -= 1;
        if (depth === 0) {
          try {
            const value = JSON.parse(text.slice(start, index + 1));
            return value && typeof value === "object" ? (value as Record<string, unknown>) : null;
          } catch {
            break;
          }
        }
      }
    }
  }
  return null;
}

/** YouTube's `{ simpleText }` / `{ runs: [{ text }] }` localisation shapes. */
function readText(value: unknown): string {
  if (typeof value === "string") return value.trim();
  if (!value || typeof value !== "object") return "";
  const record = value as Record<string, unknown>;
  if (typeof record.simpleText === "string") return record.simpleText.trim();
  if (Array.isArray(record.runs)) {
    return record.runs
      .map((run) => (run && typeof run === "object" ? String((run as Record<string, unknown>).text || "") : ""))
      .join("")
      .trim();
  }
  return "";
}

export type RawTrack = {
  baseUrl: string;
  language: string;
  label: string;
  autoGenerated: boolean;
  /**
   * The User-Agent of the InnerTube client that handed us this URL. A caption
   * URL produced for ANDROID is 403'd when it is fetched with a browser's
   * User-Agent — so the download repeats the request with the UA that earned
   * it. Empty for tracks read off the watch page / the legacy list endpoint.
   */
  userAgent?: string;
  /** The client's own `c` + `cver`, appended to the caption URL. */
  clientName?: string;
  clientVersion?: string;
};

type RawPlayer = {
  tracks: RawTrack[];
  title: string;
  playability: string;
  reason: string;
  /**
   * Did this response look COMPLETE? YouTube's bot mitigation does not always
   * say "you are a bot": very often it answers `playabilityStatus: OK` with
   * the video's title, but silently omits `streamingData` and `captions`.
   * Reading that stripped answer as "the video has no captions" is exactly
   * the lie this module used to tell the learner — so completeness is now
   * tracked and only a COMPLETE answer can prove captions are absent.
   */
  complete: boolean;
};

function readPlayerResponse(player: unknown, source?: { userAgent?: string; clientName?: string; clientVersion?: string }): RawPlayer {
  const record = (player && typeof player === "object" ? player : {}) as Record<string, unknown>;
  const details = (record.videoDetails || {}) as Record<string, unknown>;
  const playabilityStatus = (record.playabilityStatus || {}) as Record<string, unknown>;
  const captions = (record.captions || {}) as Record<string, unknown>;
  const renderer = (captions.playerCaptionsTracklistRenderer || {}) as Record<string, unknown>;
  const list = Array.isArray(renderer.captionTracks) ? renderer.captionTracks : [];
  const seen = new Set<string>();
  const tracks: RawTrack[] = [];
  for (const item of list) {
    if (!item || typeof item !== "object") continue;
    const raw = item as Record<string, unknown>;
    const baseUrl = String(raw.baseUrl || "").trim();
    const language = String(raw.languageCode || "").trim().toLowerCase();
    const label = readText(raw.name) || transcriptLanguageLabel(language);
    const autoGenerated = String(raw.kind || "").toLowerCase() === "asr" || /auto[- ]?generated/i.test(label);
    if (!baseUrl || !language) continue;
    if (!isAllowedCaptionUrl(baseUrl)) continue;
    const key = `${language}|${autoGenerated ? "asr" : "manual"}`;
    if (seen.has(key)) continue;
    seen.add(key);
    tracks.push({
      baseUrl,
      language,
      label,
      autoGenerated,
      userAgent: source?.userAgent || "",
      clientName: source?.clientName || "",
      clientVersion: source?.clientVersion || "",
    });
  }
  const title = String(details.title || "").trim();
  const hasStreamingData = Boolean(record.streamingData && typeof record.streamingData === "object");
  return {
    tracks,
    title,
    playability: String(playabilityStatus.status || "").trim(),
    reason: String(playabilityStatus.reason || "").trim(),
    // A complete answer carries the video's own detail AND its streams. One
    // that carries neither was stripped by YouTube, not emptied by the uploader.
    complete: Boolean(title) && hasStreamingData,
  };
}

/** Caption URLs must stay on YouTube (never an open relay / SSRF hole). */
export function isAllowedCaptionUrl(rawUrl: string): boolean {
  try {
    const url = new URL(rawUrl.startsWith("//") ? `https:${rawUrl}` : rawUrl);
    if (url.protocol !== "https:") return false;
    return CAPTION_HOST.test(url.hostname);
  } catch {
    return false;
  }
}

/* ── Fetching with a shared deadline ────────────────────────────────────── */

type Deadline = { at: number };

const createDeadline = (): Deadline => ({ at: Date.now() + REQUEST_BUDGET_MS });

const remainingMs = (deadline: Deadline): number => Math.max(0, deadline.at - Date.now());

async function fetchWithDeadline(
  url: string,
  init: RequestInit,
  deadline: Deadline,
): Promise<Response> {
  const budget = Math.min(SINGLE_FETCH_MS, remainingMs(deadline));
  if (budget <= 0) throw new TranscriptError("timeout", "The transcript request ran out of time.");
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), budget);
  try {
    return await fetch(url, { ...init, signal: controller.signal, redirect: "follow" });
  } catch (error) {
    if ((error as { name?: string })?.name === "AbortError") {
      throw new TranscriptError("timeout", "YouTube took too long to answer.");
    }
    throw new TranscriptError("fetch_failed", "YouTube could not be reached.");
  } finally {
    clearTimeout(timer);
  }
}

