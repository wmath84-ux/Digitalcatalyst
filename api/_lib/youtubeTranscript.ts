/**
 * "English (auto-generated)" → "en". The panel does not hand back a language
 * CODE, only its own footer sentence, so the name is matched back onto the
 * codes the page's picker speaks. Unknown names keep the words themselves.
 */
export function languageCodeFromLabel(label: string): string {
  const words = String(label || "")
    .replace(/\((?:auto[- ]?generated|generated|original)\)/i, "")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
  if (!words) return "";
  if (/^[a-z]{2,3}(?:-[a-z0-9]{2,8})?$/i.test(words)) return words;
  for (const code of KNOWN_LANGUAGE_CODES) {
    const name = transcriptLanguageLabel(code).toLowerCase();
    if (name === words) return code;
  }
  return "";
}

/**
 * Walk the panel's answer and lift out every segment. A recursive walk (rather
 * than a hard-coded path) is deliberate: YouTube re-shapes this renderer often,
 * and a segment is unmistakable — it is the object that carries `startMs`
 * together with a `snippet`.
 */
export function collectPanelCues(node: unknown, out: RawCue[] = []): RawCue[] {
  if (!node || typeof node !== "object") return out;
  if (Array.isArray(node)) {
    for (const item of node) collectPanelCues(item, out);
    return out;
  }
  const record = node as Record<string, unknown>;
  const startRaw = record.startMs;
  if ((typeof startRaw === "string" || typeof startRaw === "number") && record.snippet) {
    const text = cleanCueText(readText(record.snippet));
    if (text) {
      const start = Math.max(0, Number(startRaw) / 1000);
      const end = Math.max(start, Number(record.endMs ?? 0) / 1000);
      out.push({ start, end, text });
    }
  }
  for (const value of Object.values(record)) collectPanelCues(value, out);
  return out;
}

/** The panel's own footer sentence — "English (auto-generated)", "हिन्दी"… */
function readPanelFooter(node: unknown, depth = 0): string {
  if (!node || typeof node !== "object" || depth > 24) return "";
  if (Array.isArray(node)) {
    for (const item of node) {
      const found = readPanelFooter(item, depth + 1);
      if (found) return found;
    }
    return "";
  }
  const record = node as Record<string, unknown>;
  if (record.transcriptFooterRenderer && typeof record.transcriptFooterRenderer === "object") {
    const footer = record.transcriptFooterRenderer as Record<string, unknown>;
    const text = readText(footer.initialDescription);
    if (text) return text;
  }
  for (const value of Object.values(record)) {
    const found = readPanelFooter(value, depth + 1);
    if (found) return found;
  }
  return "";
}

async function readTranscriptPanel(
  videoId: string,
  deadline: Deadline,
  reports?: LayerReport[],
): Promise<PanelTranscript | null> {
  const params = buildTranscriptParams(videoId);
  const report = (entry: LayerReport) => {
    reports?.push(entry);
    return entry;
  };
  if (!params) return null;
  let response: Response;
  try {
    response = await fetchWithDeadline(
      INNERTUBE_TRANSCRIPT_URL,
      {
        method: "POST",
        headers: {
          "content-type": "application/json",
          "user-agent": WEB_USER_AGENT,
          "accept-language": "en-US,en;q=0.9",
          origin: "https://www.youtube.com",
          referer: `https://www.youtube.com/watch?v=${videoId}`,
          "x-youtube-client-name": "1",
          "x-youtube-client-version": PANEL_CLIENT_VERSION,
        },
        body: JSON.stringify({
          context: { client: { clientName: "WEB", clientVersion: PANEL_CLIENT_VERSION, hl: "en", gl: "US" } },
          params,
        }),
      },
      deadline,
    );
  } catch (error) {
    if (error instanceof TranscriptError && error.code === "too_many_requests") {
      report({ source: "get_transcript", answered: false, tracks: 0, playability: "", reason: "", blocked: true, complete: false, note: "HTTP 429" });
      throw error;
    }
    report({
      source: "get_transcript",
      answered: false,
      tracks: 0,
      playability: "",
      reason: "",
      blocked: false,
      complete: false,
      note: error instanceof Error ? error.message : "unreachable",
    });
    return null;
  }
  if (response.status === 429) {
    report({ source: "get_transcript", answered: false, tracks: 0, playability: "", reason: "", blocked: true, complete: false, note: "HTTP 429" });
    throw new TranscriptError("too_many_requests", "YouTube is temporarily limiting transcript requests from this network. Please try again in a little while.");
  }
  if (!response.ok) {
    report({ source: "get_transcript", answered: false, tracks: 0, playability: "", reason: "", blocked: false, complete: false, note: `HTTP ${response.status}` });
    return null;
  }
  let json: unknown = null;
  try {
    json = await response.json();
  } catch {
    json = null;
  }
  if (!json) {
    report({ source: "get_transcript", answered: false, tracks: 0, playability: "", reason: "", blocked: false, complete: false, note: "unparseable body" });
    return null;
  }
  const cues = collectPanelCues(json);
  const footer = readPanelFooter(json);
  const autoGenerated = /auto[- ]?generated|\(generated\)/i.test(footer);
  const label = footer.replace(/\s*\((?:auto[- ]?generated|generated)\)\s*/i, "").trim();
  const language = languageCodeFromLabel(footer) || (label ? label.toLowerCase().replace(/\s+/g, "-") : "");
  report({
    source: "get_transcript",
    answered: true,
    tracks: cues.length ? 1 : 0,
    playability: "OK",
    reason: "",
    blocked: false,
    // The panel is YouTube's own transcript UI: when it answers with nothing,
    // there really is nothing to show.
    complete: cues.length > 0,
    note: cues.length ? `${cues.length} panel segments (${footer || "no footer"})` : "panel answered with no segments",
  });
  if (!cues.length) return null;
  return { cues, language, label: label || transcriptLanguageLabel(language), autoGenerated, title: "" };
}

/* ── The orchestration ──────────────────────────────────────────────────── */

/**
 * Fetch one video's transcript.
 *
 * THE CHAIN — every layer is tried in order, and each one records what it
 * actually saw:
 *
 *   1. InnerTube `player`, wave 1 (ANDROID · WEB · TVHTML5_SIMPLY_EMBEDDED),
 *      raced in parallel;
 *   2. InnerTube `player`, wave 2 (IOS · MWEB · WEB_EMBEDDED_PLAYER) — only if
 *      wave 1 came back without caption tracks;
 *   3. the caption download for the best track (JSON3 → default XML/srv3 →
 *      WebVTT, always with the User-Agent of the client that minted the URL);
 *   4. the public watch page's `ytInitialPlayerResponse`;
 *   5. YouTube's own transcript panel (`get_transcript`) — the lines
 *      themselves, no signed URL involved;
 *   6. the legacy `timedtext?type=list` endpoint.
 *
 * THE HONESTY RULE, which is the reason this function was rewritten:
 *
 *   `no_captions` used to mean "we found no caption tracks", and YouTube's bot
 *   mitigation produces exactly that answer — a `playabilityStatus: OK` with
 *   the video's title but the caption list quietly removed — from a
 *   datacentre IP. So the page told learners "This video has no captions" for
 *   videos that plainly do. Now a caption-less verdict needs PROOF: either one
 *   COMPLETE answer (title + streams present, captions absent) or two
 *   independent layers agreeing. Anything less is reported as a throttle or a
 *   read failure, both of which the page retries — and both of which let the
 *   browser-side fallback run on the learner's own (unblocked) IP.
 */
export async function fetchYouTubeTranscript(
  videoIdInput: string,
  requestedLanguage?: string,
  options?: { diagnostics?: boolean },
): Promise<TranscriptPayload> {
  const videoId = parseYouTubeVideoId(videoIdInput);
  if (!videoId) throw new TranscriptError("bad_video", "That is not a YouTube video id.");

  const requested = String(requestedLanguage || "").trim().toLowerCase();
  const cacheKey = `${videoId}|${requested || "auto"}`;
  const cached = readCache(cacheKey);
  if (cached) return cached;

  const deadline = createDeadline();
  const reports: LayerReport[] = [];
  const withReports = (error: TranscriptError): TranscriptError => {
    error.reports = reports;
    return error;
  };
  function fail(code: TranscriptErrorCode, message: string): never {
    throw withReports(new TranscriptError(code, message));
  }

  const buildPayload = (input: {
    title: string;
    language: string;
    label: string;
    autoGenerated: boolean;
    tracks: RawTrack[];
    cues: RawCue[];
    strategy: string;
  }): TranscriptPayload | null => {
    const allSegments = groupTranscriptCues(input.cues);
    if (!allSegments.length) return null;
    const truncated = allSegments.length > MAX_SEGMENTS;
    return {
      videoId,
      title: input.title,
      language: input.language,
      languageLabel: input.label || transcriptLanguageLabel(input.language),
      autoGenerated: input.autoGenerated,
      tracks: input.tracks.map((track) => ({
        language: track.language,
        label: track.label || transcriptLanguageLabel(track.language),
        autoGenerated: track.autoGenerated,
      })),
      segments: truncated ? allSegments.slice(0, MAX_SEGMENTS) : allSegments,
      truncated,
      fetchedAt: Date.now(),
      strategy: input.strategy,
      ...(options?.diagnostics ? { attempts: reports } : {}),
    };
  };

  const finish = (payload: TranscriptPayload): TranscriptPayload => {
    writeCache(cacheKey, payload);
    return payload;
  };

  let player: RawPlayer | null = null;
  let bestTitle = "";
  const noteTitle = (candidate: RawPlayer | null) => {
    if (candidate?.title && !bestTitle) bestTitle = candidate.title;
  };

  /* ── 1 + 2. InnerTube, in two parallel waves ─────────────────────────── */
  try {
    player = await readInnerTubeAllClients(videoId, deadline, reports);
  } catch (error) {
    if (error instanceof TranscriptError && error.code === "too_many_requests") fail(error.code, error.message);
    player = null;
  }
  noteTitle(player);

  /* ── 3. The caption download for the best track we have ──────────────── */
  if (player?.tracks.length) {
    const chosen = chooseCaptionTrack(player.tracks, requested);
    if (chosen) {
      try {
        const cues = await fetchCaptionCues(chosen, deadline);
        const payload = buildPayload({
          title: player.title || bestTitle,
          language: chosen.language,
          label: chosen.label,
          autoGenerated: chosen.autoGenerated,
          tracks: player.tracks,
          cues,
          strategy: `caption-track(${chosen.language})`,
        });
        if (payload) return finish(payload);
      } catch (error) {
        const code = error instanceof TranscriptError ? error.code : "fetch_failed";
        reports.push({
          source: "caption-download",
          answered: false,
          tracks: player.tracks.length,
          playability: player.playability,
          reason: "",
          blocked: code === "too_many_requests",
          complete: false,
          note: error instanceof Error ? error.message : "caption download failed",
        });
      }
    }
  }

  /* ── 4. The public watch page ────────────────────────────────────────── */
  if (remainingMs(deadline) > 1_000) {
    try {
      const page = await readWatchPage(videoId, deadline, reports);
      noteTitle(page);
      if (page?.tracks.length) {
        player = page;
        const chosen = chooseCaptionTrack(page.tracks, requested);
        if (chosen) {
          try {
            const cues = await fetchCaptionCues(chosen, deadline);
            const payload = buildPayload({
              title: page.title || bestTitle,
              language: chosen.language,
              label: chosen.label,
              autoGenerated: chosen.autoGenerated,
              tracks: page.tracks,
              cues,
              strategy: `watch-page(${chosen.language})`,
            });
            if (payload) return finish(payload);
          } catch (error) {
            const code = error instanceof TranscriptError ? error.code : "fetch_failed";
            reports.push({
              source: "caption-download(watch-page)",
              answered: false,
              tracks: page.tracks.length,
              playability: page.playability,
              reason: "",
              blocked: code === "too_many_requests",
              complete: false,
              note: error instanceof Error ? error.message : "caption download failed",
            });
          }
        }
      } else if (!player) {
        player = page;
      }
    } catch (error) {
      // A captcha / 429 here is recorded as a block; the panel and the legacy
      // list are still worth one try each, and the final verdict below never
      // hides the block.
      if (error instanceof TranscriptError && error.code !== "too_many_requests") {
        reports.push({ source: "watch-page", answered: false, tracks: 0, playability: "", reason: "", blocked: false, complete: false, note: error.message });
      }
    }
  }

  /* ── 5. YouTube's own transcript panel ───────────────────────────────── */
  if (remainingMs(deadline) > 1_000) {
    try {
      const panel = await readTranscriptPanel(videoId, deadline, reports);
      if (panel?.cues.length) {
        const payload = buildPayload({
          title: bestTitle,
          language: panel.language,
          label: panel.label,
          autoGenerated: panel.autoGenerated,
          tracks: [
            {
              baseUrl: "",
              language: panel.language || "und",
              label: panel.label,
              autoGenerated: panel.autoGenerated,
            },
          ],
          cues: panel.cues,
          strategy: "get_transcript-panel",
        });
        if (payload) return finish(payload);
      }
    } catch (error) {
      if (error instanceof TranscriptError && error.code !== "too_many_requests") {
        reports.push({ source: "get_transcript", answered: false, tracks: 0, playability: "", reason: "", blocked: false, complete: false, note: error.message });
      }
    }
  }

  /* ── 6. The legacy timedtext list ────────────────────────────────────── */
  // Skipped once YouTube has throttled this request: the legacy endpoint sits
  // behind the same wall, and a second 429 buys nothing but latency.
  const alreadyBlocked = reports.some((report) => report.blocked);
  if (!alreadyBlocked && remainingMs(deadline) > 1_000) {
    try {
      const timed = await readTimedTextList(videoId, deadline);
      if (timed?.tracks.length) {
        reports.push({
          source: "timedtext-list",
          answered: true,
          tracks: timed.tracks.length,
          playability: timed.playability,
          reason: "",
          blocked: false,
          complete: false,
        });
        const chosen = chooseCaptionTrack(timed.tracks, requested);
        if (chosen) {
          try {
            const cues = await fetchCaptionCues(chosen, deadline);
            const payload = buildPayload({
              title: bestTitle,
              language: chosen.language,
              label: chosen.label,
              autoGenerated: chosen.autoGenerated,
              tracks: timed.tracks,
              cues,
              strategy: `timedtext(${chosen.language})`,
            });
            if (payload) return finish(payload);
          } catch (error) {
            const code = error instanceof TranscriptError ? error.code : "fetch_failed";
            reports.push({
              source: "caption-download(timedtext)",
              answered: false,
              tracks: timed.tracks.length,
              playability: "",
              reason: "",
              blocked: code === "too_many_requests",
              complete: false,
              note: error instanceof Error ? error.message : "caption download failed",
            });
          }
        }
      } else if (timed) {
        reports.push({ source: "timedtext-list", answered: true, tracks: 0, playability: "OK", reason: "", blocked: false, complete: false, note: "empty track list" });
      }
    } catch (error) {
      const blocked = error instanceof TranscriptError && error.code === "too_many_requests";
      reports.push({
        source: "timedtext-list",
        answered: false,
        tracks: 0,
        playability: "",
        reason: "",
        blocked,
        complete: false,
        note: error instanceof Error ? error.message : "unreachable",
      });
    }
  }

  /* ── The verdict ─────────────────────────────────────────────────────── */
  const blocked = reports.some((report) => report.blocked);
  // One layer family = one opinion. Six InnerTube clients repeating the same
  // stripped answer must not be mistaken for six independent confirmations.
  const family = (source: string) => source.split("(")[0].split(":")[0].replace(/-download$/, "");
  const cleanStatus = (status: string) => {
    const upper = String(status || "").toUpperCase();
    return upper === "" || upper === "OK";
  };
  const emptyOpinions = new Set(
    reports
      .filter((report) => report.answered && report.tracks === 0 && !report.blocked && cleanStatus(report.playability))
      .map((report) => family(report.source)),
  );
  const authoritativeEmpty = reports.filter(
    (report) => report.answered && report.complete && report.tracks === 0 && !report.blocked && cleanStatus(report.playability),
  );
  const unavailable = reports.filter((report) => {
    const status = String(report.playability || "").toUpperCase();
    return report.answered && Boolean(status) && !cleanStatus(status) && !isBotOrLoginReason(report.reason);
  });

  if (blocked) {
    fail(
      "too_many_requests",
      "YouTube is temporarily limiting transcript requests from this network. Please try again in a little while.",
    );
  }
  if (authoritativeEmpty.length || emptyOpinions.size >= 2) {
    fail(
      "no_captions",
      "This video has no captions (neither manual nor auto-generated), so there is no transcript to show.",
    );
  }
  if (unavailable.length) {
    fail(
      "video_unavailable",
      "YouTube didn't share this video's player data. It may be private, age-restricted or region-locked.",
    );
  }
  // Nothing proved anything — that is a READ FAILURE, not a caption-less
  // video. The page retries, and the browser-side fallback gets its turn on
  // the learner's own IP.
  fail(
    "fetch_failed",
    "YouTube's player data could not be read from this server. Please try again in a moment.",
  );
}

/* ── The serverless handler ─────────────────────────────────────────────── */

const first = (value: string | string[] | undefined): string =>
  Array.isArray(value) ? String(value[0] || "") : String(value || "");

const statusFor = (code: TranscriptErrorCode): number => {
  switch (code) {
    case "bad_video":
      return 400;
    case "video_unavailable":
    case "no_captions":
      return 404;
    case "no_transcript":
      return 422;
    case "too_many_requests":
      return 429;
    case "timeout":
      return 504;
    default:
      return 502;
  }
};

/**
 * `GET /api/youtube-transcript?v=<id>&lang=<code>`
 * Answers `{ ok: true, …TranscriptPayload }` or `{ ok: false, code, error }`.
 */
export async function handleYouTubeTranscript(
  req: TranscriptRequestLike,
  res: TranscriptResponseLike,
): Promise<void> {
  const method = String(req.method || "GET").toUpperCase();
  if (method !== "GET" && method !== "HEAD") {
    res.status(405).json({ ok: false, code: "method_not_allowed", error: "Use GET." });
    return;
  }
  const query = req.query || {};
  const rawId = first(query.v) || first(query.videoId) || first(query.url) || first(query.id);
  const videoId = parseYouTubeVideoId(rawId);
  if (!videoId) {
    res.status(400).json({
      ok: false,
      code: "bad_video",
      error: "Pass ?v=<11-character YouTube video id> (a watch URL also works).",
    });
    return;
  }
  const language = first(query.lang).trim().toLowerCase().slice(0, 35);
  // `?diagnostics=1` attaches the layer-by-layer trail to the answer. The page
  // asks for it on a failure retry so the learner (and the owner) can see
  // WHICH layer said what — the difference between "no captions" and
  // "YouTube throttled us" is invisible otherwise.
  const diagnostics = /^(1|true|yes)$/i.test(first(query.diagnostics).trim());
  try {
    const payload = await fetchYouTubeTranscript(videoId, language || undefined, { diagnostics });
    res.setHeader("Cache-Control", "public, s-maxage=3600, stale-while-revalidate=86400");
    res.setHeader("Content-Type", "application/json; charset=utf-8");
    res.status(200).json({ ok: true, ...payload });
  } catch (error) {
    const transcriptError = error instanceof TranscriptError
      ? error
      : new TranscriptError("fetch_failed", error instanceof Error ? error.message : "The transcript could not be fetched.");
    res.setHeader("Cache-Control", "no-store");
    res.setHeader("Content-Type", "application/json; charset=utf-8");
    res.status(statusFor(transcriptError.code)).json({
      ok: false,
      code: transcriptError.code,
      error: transcriptError.message,
      videoId,
      // Always sent on a failure: it is small, and it is the only evidence
      // the page can show about what YouTube actually answered.
      attempts: (transcriptError.reports || []).map((report) => ({
        source: report.source,
        answered: report.answered,
        tracks: report.tracks,
        playability: report.playability,
        blocked: report.blocked,
        note: report.note || "",
      })),
    });
  }
}
