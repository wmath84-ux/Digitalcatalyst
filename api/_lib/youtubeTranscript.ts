export type TranscriptErrorCode =
  | "bad_video"
  | "video_unavailable"
  | "no_captions"
  | "no_transcript"
  | "too_many_requests"
  | "timeout"
  | "fetch_failed";

export class TranscriptError extends Error {
  code: TranscriptErrorCode;
  /**
   * What every layer actually answered on the way to this failure. The page
   * shows it under "Details", which is how a learner (or the owner) can tell
   * "this video genuinely has no captions" from "YouTube throttled our
   * server" without reading a single log line.
   */
  reports?: LayerReport[];

  constructor(code: TranscriptErrorCode, message?: string) {
    super(message || code);
    this.name = "TranscriptError";
    this.code = code;
  }
}

