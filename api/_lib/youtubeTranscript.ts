// api/_lib/youtubeTranscript.ts
//
// "VIDEO KA POORA TEXT, TIME STAMP KE SAATH" — the Course Player's transcript
// service.
//
// The owner pointed at `InigoMarin/yttranscript` (a Python CLI that downloads
// YouTube transcripts and falls back to Whisper). The Course Player cannot run
// a Python CLI, so this module brings the ONE part the tab actually needs into
// the app's own serverless function — the same public caption pipeline, with no
// extra dependency and no API key:
//
//   1. Ask YouTube's InnerTube player API (multiple clients — ANDROID, WEB,
//      IOS, MWEB — the same public clients `youtube-transcript` libraries use)
//      for the caption track list. ANDROID is tried first because it is the
//      most permissive, but WEB/IOS often succeed when ANDROID is flagged.
//   2. If that fails, read the public watch page and parse
//      `ytInitialPlayerResponse` (balanced-brace scan, never a greedy regex).
//   3. If that also fails, try the legacy timedtext list endpoint
//      `/api/timedtext?type=list&v=ID` which sometimes bypasses InnerTube bot
//      checks entirely.
//   4. Fetch the chosen track as JSON3 (`&fmt=json3`) and fall back to the
//      classic / srv3 XML shapes when a track ignores the format parameter.
//   5. Merge YouTube's 2–3 second caption bites into readable ~8–15 second
//      lines. Every line keeps the START of its first caption, which is what
//      the page's timestamp button seeks to.
//
// ── What it deliberately does NOT do ──────────────────────────────────────
// No audio download, no ffmpeg, no Whisper. Serverless functions have no
// persistent disk and a short execution budget, and shipping an audio
// transcriber would turn every lesson into a multi-minute job. A video with
// captions (manual OR auto-generated) always works; one with none answers
// `no_captions` and the tab says so plainly.
//
// ── Safety ────────────────────────────────────────────────────────────────
// · Only an 11-character YouTube id is accepted (no arbitrary URLs).
// · Caption URLs are host-locked to youtube.com / youtube-nocookie.com.
// · Every outbound fetch has a deadline; the whole request is budgeted to
//   finish inside Vercel's default function window.
// · Results are cached in-process for 30 minutes, so a re-opened tab (and a
//   second learner on the same warm function) is instant.
//
// The file is a PRIVATE `_lib` helper: `api/referral-leaderboard.ts` dispatches
// it under `/api/youtube-transcript` (see vercel.json), which keeps the project
// inside Vercel Hobby's 12-function cap.

