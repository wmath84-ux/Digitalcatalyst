// tests/coursePlayerTranscriptApi.test.mjs
//
// The transcript service, exercised end to end against a fake YouTube.
//
// The contract suite pins the parsers; this one pins the ORCHESTRATION the
// browser never sees:
//
//   InnerTube player  →  caption track  →  JSON3 / srv3 / classic XML  →  lines
//   watch-page HTML   →  `ytInitialPlayerResponse`  →  the same caption path
//   every failure     →  the code + HTTP status the Transcript page renders
//
// `fetch` is replaced with a scripted responder, and the in-process cache is
// cleared before every case, so this suite is hermetic and never touches
// youtube.com — which is exactly what lets it run in CI.

import test from "node:test";
import assert from "node:assert/strict";
import {
  clearTranscriptCache,
  fetchYouTubeTranscript,
  TranscriptError,
} from "../api/_lib/youtubeTranscript.ts";

const originalFetch = globalThis.fetch;

const jsonResponse = (body, status = 200) => ({
  ok: status >= 200 && status < 300,
  status,
  async json() {
    return body;
  },
  async text() {
    return JSON.stringify(body);
  },
});

const textResponse = (body, status = 200) => ({
  ok: status >= 200 && status < 300,
  status,
  async json() {
    return JSON.parse(body);
  },
  async text() {
    return body;
  },
});

const captionTrack = (language = "en", kind = "") => ({
  baseUrl: `https://www.youtube.com/api/timedtext?lang=${language}&v=dQw4w9WgXcQ${kind ? `&kind=${kind}` : ""}`,
  languageCode: language,
  kind: kind || undefined,
  name: { simpleText: language === "hi" ? "Hindi" : "English" },
});

const playerBody = ({ tracks = [], title = "A lecture", status = "OK", reason = "" } = {}) => ({
  playabilityStatus: reason ? { status, reason } : { status },
  videoDetails: { title },
  captions: {
    playerCaptionsTracklistRenderer: { captionTracks: tracks },
  },
});

const json3 = JSON.stringify({
  events: [
    { tStartMs: 0, dDurationMs: 1400, segs: [{ utf8: "Hello " }, { utf8: "world." }] },
    // A 2.6s silence is a new thought — see groupTranscriptCues.
    { tStartMs: 4000, dDurationMs: 1400, segs: [{ utf8: "This is a test." }] },
  ],
});

const classicXml =
  '<transcript><text start="2" dur="1.4">First thought.</text><text start="20" dur="2">Second thought.</text></transcript>';

/**
 * Script a fake YouTube. `routes` maps a matcher to a responder; the first
 * matching route answers. Anything unmatched fails loudly, so a test can never
 * silently exercise the wrong branch.
 */
function stubFetch(routes) {
  const calls = [];
  globalThis.fetch = async (url, init = {}) => {
    const href = String(url);
    calls.push({ url: href, method: String(init.method || "GET") });
    for (const [match, respond] of routes) {
      if (match(href, init)) return respond(href, init);
    }
    throw new Error(`Unexpected fetch: ${href}`);
  };
  return calls;
}

const isInnerTube = (url) => url.includes("/youtubei/v1/player");
const isWatchPage = (url) => url.includes("/watch?");
const isCaption = (url) => url.includes("/api/timedtext");

test.afterEach(() => {
  globalThis.fetch = originalFetch;
  clearTranscriptCache();
});

test("InnerTube → chosen track → JSON3 becomes timestamped lines", async () => {
  const calls = stubFetch([
    [isInnerTube, () => jsonResponse(playerBody({ tracks: [captionTrack("en")] }))],
    [isCaption, () => textResponse(json3)],
  ]);

  const transcript = await fetchYouTubeTranscript("dQw4w9WgXcQ");

  assert.equal(transcript.videoId, "dQw4w9WgXcQ");
  assert.equal(transcript.title, "A lecture");
  assert.equal(transcript.language, "en");
  assert.equal(transcript.languageLabel, "English");
  assert.equal(transcript.autoGenerated, false);
  assert.equal(transcript.segments.length, 2);
  assert.equal(transcript.segments[0].start, 0);
  assert.equal(transcript.segments[0].text, "Hello world.");
  // The caption request must ask for JSON3 explicitly.
  const captionCall = calls.find((call) => isCaption(call.url));
  assert.ok(captionCall, "a caption track was downloaded");
  assert.match(captionCall.url, /[?&]fmt=json3(&|$)/);

  // A second read is served from the in-process cache: no new network calls.
  const before = calls.length;
  const again = await fetchYouTubeTranscript("dQw4w9WgXcQ");
  assert.equal(again.segments.length, 2);
  assert.equal(calls.length, before, "the warm cache answers without refetching");
});

test("InnerTube without captions falls back to the watch page's player JSON", async () => {
  const html = `<html><script>var ytInitialPlayerResponse = ${JSON.stringify(
    playerBody({ tracks: [captionTrack("hi")], title: "Watch page title" }),
  )};</script></html>`;
  const calls = stubFetch([
    [isInnerTube, () => jsonResponse(playerBody({ tracks: [] }))],
    [isWatchPage, () => textResponse(html)],
    [isCaption, () => textResponse(classicXml)],
  ]);

  const transcript = await fetchYouTubeTranscript("dQw4w9WgXcQ");

  assert.equal(calls.filter((call) => isWatchPage(call.url)).length, 1, "the watch page was consulted");
  assert.equal(transcript.title, "Watch page title");
  assert.equal(transcript.language, "hi");
  assert.equal(transcript.languageLabel, "Hindi");
  assert.deepEqual(
    transcript.segments.map((segment) => [segment.start, segment.text]),
    [[2, "First thought."], [20, "Second thought."]],
  );
});

test("an unavailable video is not reported as an uncaptioned one", async () => {
  stubFetch([
    [isInnerTube, () => jsonResponse(playerBody({ tracks: [], status: "ERROR", reason: "Video unavailable" }))],
    [isWatchPage, () => textResponse("", 500)],
  ]);

  await assert.rejects(fetchYouTubeTranscript("dQw4w9WgXcQ"), (error) => {
    assert.ok(error instanceof TranscriptError);
    assert.equal(error.code, "video_unavailable");
    // The message is now user-friendly, not the raw YouTube reason — the
    // important contract is the code, so the page can explain it.
    assert.ok(
      typeof error.message === "string" && error.message.length > 0,
      "an explanatory message is present",
    );
    return true;
  });
});

test("a bot check maps to the rate-limit code the page explains", async () => {
  stubFetch([
    [isInnerTube, () => jsonResponse(playerBody({
      tracks: [],
      status: "LOGIN_REQUIRED",
      reason: "Sign in to confirm you're not a bot",
    }))],
    [isWatchPage, () => textResponse("", 500)],
  ]);

  await assert.rejects(fetchYouTubeTranscript("dQw4w9WgXcQ"), (error) => {
    assert.equal(error.code, "too_many_requests");
    return true;
  });
});

test("a video with no caption track at all says no_captions", async () => {
  stubFetch([
    [isInnerTube, () => jsonResponse(playerBody({ tracks: [] }))],
    [isWatchPage, () => textResponse(`<script>var ytInitialPlayerResponse = ${JSON.stringify(playerBody({ tracks: [] }))};</script>`)],
  ]);

  await assert.rejects(fetchYouTubeTranscript("dQw4w9WgXcQ"), (error) => {
    assert.equal(error.code, "no_captions");
    return true;
  });
});

test("a 429 caption download stops at the rate-limit code instead of retrying blindly", async () => {
  const calls = stubFetch([
    [isInnerTube, () => jsonResponse(playerBody({ tracks: [captionTrack("en")] }))],
    [isCaption, () => textResponse("Too Many Requests", 429)],
  ]);

  await assert.rejects(fetchYouTubeTranscript("dQw4w9WgXcQ"), (error) => {
    assert.equal(error.code, "too_many_requests");
    return true;
  });
  // One player POST + one caption GET; the plain-track retry never ran.
  assert.equal(calls.filter((call) => isCaption(call.url)).length, 1);
});

test("the requested language wins, and an unsupported one falls back politely", async () => {
  stubFetch([
    [isInnerTube, () => jsonResponse(playerBody({ tracks: [captionTrack("en"), captionTrack("hi")] }))],
    [isCaption, (_url) => textResponse(json3)],
  ]);

  const hindi = await fetchYouTubeTranscript("dQw4w9WgXcQ", "hi");
  assert.equal(hindi.language, "hi");

  // A language the video does not carry must not fail the page: the picker
  // still defaults to the manual English track.
  const klingon = await fetchYouTubeTranscript("dQw4w9WgXcQ", "tlh");
  assert.equal(klingon.language, "en");
});

test("a 429 from YouTube's player stops before the watch-page fallback", async () => {
  const calls = stubFetch([
    [isInnerTube, () => textResponse("Too Many Requests", 429)],
  ]);

  await assert.rejects(fetchYouTubeTranscript("dQw4w9WgXcQ"), (error) => {
    assert.equal(error.code, "too_many_requests");
    return true;
  });
  assert.equal(calls.filter((call) => isWatchPage(call.url)).length, 0, "no second request to the same wall");
});

test("a reCAPTCHA watch page is reported as a rate limit, not as missing captions", async () => {
  stubFetch([
    [isInnerTube, () => jsonResponse(playerBody({ tracks: [] }))],
    [isWatchPage, () => textResponse('<html><div class="g-recaptcha"></div></html>')],
  ]);

  await assert.rejects(fetchYouTubeTranscript("dQw4w9WgXcQ"), (error) => {
    assert.equal(error.code, "too_many_requests");
    return true;
  });
});
