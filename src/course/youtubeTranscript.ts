// src/course/youtubeTranscript.ts
//
// The browser half of the Course Player's Transcript tab.
//
// It owns three things and nothing else:
//   1. WHICH video is on screen — `youTubeVideoIdForFile()` reads the id from
//      every shape a course file can carry (youtubeVideoId, watch URL, embed
//      URL, youtu.be link).
//   2. The `/api/youtube-transcript` call, with an in-memory cache so
//      re-opening the tab (or switching modules and coming back) is instant.
//      If the server is rate-limited (YouTube bot check), it falls back to a
//      direct client-side timedtext fetch using the learner's own IP — which
//      bypasses Vercel's blocked IP.
//   3. The clock format the page renders — `[m:ss]` / `[h:mm:ss]`.
//
// The server does the YouTube work (api/_lib/youtubeTranscript.ts). Keeping it
// there is what makes the tab work on a phone without sending the learner to
// YouTube's own consent / bot walls, and what lets the transcript be cached at
// the CDN instead of re-fetched per device.

import { apiFetch } from "../utils/apiBase";
import { extractYouTubeId, getCourseFileUrl } from "../utils/courseEmbed";
import type { CourseFile } from "../types/course";

export type TranscriptSegment = {
  start: number;
  duration: number;
  text: string;
};

export type TranscriptTrackInfo = {
  language: string;
  label: string;
  autoGenerated: boolean;
};

export type TranscriptData = {
  videoId: string;
  title: string;
  language: string;
  languageLabel: string;
  autoGenerated: boolean;
  tracks: TranscriptTrackInfo[];
  segments: TranscriptSegment[];
  truncated: boolean;
  fetchedAt: number;
};

export type TranscriptClientErrorCode =
  | "bad_video"
  | "video_unavailable"
  | "no_captions"
  | "no_transcript"
  | "too_many_requests"
  | "timeout"
  | "fetch_failed"
  | "service_unavailable"
  | "network"
  | "aborted";

export class TranscriptRequestError extends Error {
  code: TranscriptClientErrorCode;

  constructor(code: TranscriptClientErrorCode, message?: string) {
    super(message || code);
    this.name = "TranscriptRequestError";
    this.code = code;
  }
}

/** Human copy for every failure the page can meet. */
export const TRANSCRIPT_ERROR_COPY: Record<TranscriptClientErrorCode, string> = {
  bad_video: "This link doesn't look like a YouTube video, so there's no transcript to fetch.",
  video_unavailable: "YouTube didn't share this video's player data. It may be private, age-restricted or region-locked.",
  no_captions: "This video has no captions (neither manual nor auto-generated), so there is no transcript to show.",
  no_transcript: "YouTube returned an empty caption track for this video. Try another video from the library.",
  too_many_requests: "YouTube is temporarily limiting transcript requests from this network. Please try again in a little while.",
  timeout: "YouTube took too long to answer. Check your connection and try again.",
  fetch_failed: "YouTube's transcript service could not be reached just now. Try again in a moment.",
  service_unavailable: "The transcript service is not reachable from this build right now. Try again once the site is online.",
  network: "The network dropped while fetching the transcript. Check your connection and retry.",
  aborted: "The transcript request was cancelled.",
};

const transcriptCache = new Map<string, TranscriptData>();
const CACHE_LIMIT = 24;

const cacheKeyFor = (videoId: string, language?: string | null) =>
  `${videoId}|${String(language || "").trim().toLowerCase() || "auto"}`;

/** Remember a transcript for the rest of this session (and keep the map small). */
function rememberTranscript(key: string, data: TranscriptData) {
  transcriptCache.delete(key);
  transcriptCache.set(key, data);
  while (transcriptCache.size > CACHE_LIMIT) {
    const oldest = transcriptCache.keys().next().value;
    if (oldest === undefined) break;
    transcriptCache.delete(oldest);
  }
}

/** Drop a cached answer (the page's Retry button uses this). */
export function forgetTranscript(videoId: string, language?: string | null) {
  transcriptCache.delete(cacheKeyFor(videoId, language));
}

/**
 * The video id of the file currently open in the lesson pane, or "" when the
 * open resource is not a YouTube video.
 */
export function youTubeVideoIdForFile(file: CourseFile | null | undefined): string {
  if (!file) return "";
  const direct = String((file as CourseFile & { youtubeVideoId?: string }).youtubeVideoId || "").trim();
  if (/^[A-Za-z0-9_-]{11}$/.test(direct)) return direct;
  const raw = getCourseFileUrl(file);
  const fromUrl = extractYouTubeId(raw);
  if (/^[A-Za-z0-9_-]{11}$/.test(fromUrl)) return fromUrl;
  // `extractYouTubeId` covers watch / youtu.be / shorts / embed; the player
  // also accepts a live URL, and a pasted watch link can carry the id in its
  // path. Keep the page honest for those shapes too.
  const match = String(raw || "").match(/(?:v=|youtu\.be\/|embed\/|shorts\/|live\/)([A-Za-z0-9_-]{11})/);
  return match ? match[1] : "";
}

/** `4:07` for short videos, `1:04:07` once the hour rolls over. */
export function transcriptTimestamp(totalSeconds: number): string {
  const safe = Math.max(0, Math.floor(Number(totalSeconds) || 0));
  const hours = Math.floor(safe / 3600);
  const minutes = Math.floor((safe % 3600) / 60);
  const seconds = safe % 60;
  const pad = (value: number) => String(value).padStart(2, "0");
  return hours > 0 ? `${hours}:${pad(minutes)}:${pad(seconds)}` : `${minutes}:${pad(seconds)}`;
}

/**
 * The index of the line that contains `position`, via binary search. A line
 * stays active until the next one starts; before the first line, line 0.
 */
export function activeTranscriptIndex(segments: TranscriptSegment[], position: number): number {
  if (!segments.length) return -1;
  const at = Math.max(0, Number(position) || 0);
  let low = 0;
  let high = segments.length - 1;
  let answer = 0;
  while (low <= high) {
    const mid = (low + high) >> 1;
    if (segments[mid].start <= at + 0.05) {
      answer = mid;
      low = mid + 1;
    } else {
      high = mid - 1;
    }
  }
  return answer;
}

/* ── Client-side direct YouTube fallback (bypasses server IP block) ────────
   When the server is rate-limited (YouTube bot check from Vercel's IP), the
   learner's own browser IP is usually NOT blocked. So we try the legacy
   timedtext endpoints directly from the browser:

     1. GET https://www.youtube.com/api/timedtext?type=list&v=ID
        → XML list of caption tracks
     2. GET https://www.youtube.com/api/timedtext?lang=CODE&v=ID&fmt=json3
        → JSON3 cues, fallback to XML

   This is the same pipeline the server uses, but executed with the user's IP.
   If CORS blocks it (some browsers / some regions), we fail gracefully and
   the server's friendly error is what the page shows — with a retry + open
   on YouTube CTA.
*/

type RawCue = { start: number; end: number; text: string };
type RawTrack = { baseUrl: string; language: string; label: string; autoGenerated: boolean };

function clientDecodeEntities(text: string): string {
  const once = String(text || "")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&apos;/g, "'")
    .replace(/&nbsp;/g, " ")
    .replace(/&#x([0-9a-fA-F]+);/g, (_, hex: string) => String.fromCodePoint(parseInt(hex, 16)))
    .replace(/&#(\d+);/g, (_, dec: string) => String.fromCodePoint(parseInt(dec, 10)));
  return once.includes("&amp;") ? clientDecodeEntities(once) : once;
}

function clientCleanCueText(text: string): string {
  return clientDecodeEntities(text)
    .replace(/<[^>]*>/g, " ")
    .replace(/\u200b/g, "")
    .replace(/\s+/g, " ")
    .replace(/^(?:>>\s*)+/, "")
    .trim();
}

function clientParseJson3(raw: string): RawCue[] {
  let data: unknown;
  try {
    data = JSON.parse(raw);
  } catch {
    return [];
  }
  const events = (data && typeof data === "object" ? (data as { events?: unknown }).events : null);
  if (!Array.isArray(events)) return [];
  const cues: RawCue[] = [];
  for (const event of events) {
    if (!event || typeof event !== "object") continue;
    const record = event as Record<string, unknown>;
    const segs = Array.isArray(record.segs) ? record.segs : [];
    const text = clientCleanCueText(
      segs
        .map((seg) => (seg && typeof seg === "object" ? String((seg as { utf8?: unknown }).utf8 || "") : ""))
        .join(""),
    );
    if (!text) continue;
    const start = Math.max(0, Number(record.tStartMs || 0) / 1000);
    const duration = Math.max(0, Number(record.dDurationMs || 0) / 1000);
    cues.push({ start, end: start + duration, text });
  }
  return cues;
}

function clientParseXml(raw: string): RawCue[] {
  const xml = String(raw || "");
  const cues: RawCue[] = [];
  const paragraph = /<p\s+t="(\d+)"(?:\s+d="(\d+)")?[^>]*>([\s\S]*?)<\/p>/g;
  let match: RegExpExecArray | null;
  while ((match = paragraph.exec(xml)) !== null) {
    const inner = match[3] || "";
    const words: string[] = [];
    const wordRegex = /<s[^>]*>([\s\S]*?)<\/s>/g;
    let wordMatch: RegExpExecArray | null;
    while ((wordMatch = wordRegex.exec(inner)) !== null) words.push(wordMatch[1]);
    const text = clientCleanCueText(words.length ? words.join("") : inner.replace(/<[^>]*>/g, ""));
    if (!text) continue;
    const start = Math.max(0, Number(match[1]) / 1000);
    const duration = Math.max(0, Number(match[2] || 0) / 1000);
    cues.push({ start, end: start + duration, text });
  }
  if (cues.length) return cues;
  const classic = /<text\s+start="([^"]*)"(?:\s+dur="([^"]*)")?[^>]*>([\s\S]*?)<\/text>/g;
  while ((match = classic.exec(xml)) !== null) {
    const text = clientCleanCueText(match[3]);
    if (!text) continue;
    const start = Math.max(0, Number(match[1]) || 0);
    const duration = Math.max(0, Number(match[2]) || 0);
    cues.push({ start, end: start + duration, text });
  }
  return cues;
}

function clientGroupCues(cues: RawCue[]): TranscriptSegment[] {
  const segments: TranscriptSegment[] = [];
  let current: RawCue | null = null;
  const flush = () => {
    if (!current) return;
    const text = current.text.replace(/\s+/g, " ").trim();
    if (text) {
      segments.push({
        start: Math.round(current.start * 1000) / 1000,
        duration: Math.max(0, Math.round((current.end - current.start) * 1000) / 1000),
        text,
      });
    }
    current = null;
  };
  for (const cue of cues) {
    if (!cue.text) continue;
    if (!current) {
      current = { ...cue };
      continue;
    }
    const gap = cue.start - current.end;
    const sentenceEnded = /[.!?।]$/.test(current.text);
    const tooLong = cue.end - current.start > 14 || current.text.length + cue.text.length > 280;
    if (gap > 1.5 || (sentenceEnded && current.text.length >= 55) || tooLong) {
      flush();
      current = { ...cue };
      continue;
    }
    current.text = `${current.text} ${cue.text}`.replace(/\s+/g, " ").trim();
    current.end = Math.max(current.end, cue.end);
  }
  flush();
  return segments;
}

function clientChooseTrack(tracks: RawTrack[], requested?: string): RawTrack | null {
  if (!tracks.length) return null;
  const lang = String(requested || "").trim().toLowerCase();
  if (lang) {
    const exact = tracks.find((t) => t.language === lang);
    if (exact) return exact;
    const prefix = tracks.find((t) => t.language.startsWith(`${lang}-`) || lang.startsWith(`${t.language}-`));
    if (prefix) return prefix;
  }
  const manual = tracks.filter((t) => !t.autoGenerated);
  const auto = tracks.filter((t) => t.autoGenerated);
  return (
    manual.find((t) => t.language === "en" || t.language.startsWith("en-")) ||
    manual[0] ||
    auto.find((t) => t.language === "en" || t.language.startsWith("en-")) ||
    auto[0] ||
    tracks[0]
  );
}

function clientLanguageLabel(code: string): string {
  const clean = String(code || "").trim();
  if (!clean) return "Unknown";
  try {
    const names = new Intl.DisplayNames(["en"], { type: "language" });
    const label = names.of(clean) || names.of(clean.split("-")[0]) || "";
    if (label) return label;
  } catch {
    /* no Intl.DisplayNames */
  }
  const base = clean.split("-")[0];
  const fallback: Record<string, string> = {
    en: "English", hi: "Hindi", ur: "Urdu", es: "Spanish", fr: "French",
    de: "German", pt: "Portuguese", ar: "Arabic", zh: "Chinese", ja: "Japanese",
    ko: "Korean", ru: "Russian", bn: "Bengali", ta: "Tamil", te: "Telugu",
    mr: "Marathi", gu: "Gujarati", kn: "Kannada", ml: "Malayalam", pa: "Punjabi",
    id: "Indonesian", tr: "Turkish", vi: "Vietnamese", th: "Thai", it: "Italian",
  };
  return fallback[base] || clean;
}

async function clientFetchTimedTextList(videoId: string, signal?: AbortSignal): Promise<RawTrack[] | null> {
  const url = `https://www.youtube.com/api/timedtext?type=list&v=${encodeURIComponent(videoId)}&hl=en`;
  let response: Response;
  try {
    response = await fetch(url, { signal, credentials: "omit" });
  } catch {
    return null; // CORS or network — let server error be the final answer
  }
  if (response.status === 429) throw new TranscriptRequestError("too_many_requests");
  if (!response.ok) return null;
  let xml = "";
  try {
    xml = await response.text();
  } catch {
    return null;
  }
  if (/not a bot|sign in to confirm|g-recaptcha|unusual traffic/i.test(xml)) {
    throw new TranscriptRequestError("too_many_requests");
  }
  const tracks: RawTrack[] = [];
  const seen = new Set<string>();
  const trackRegex = /<track[^>]+>/g;
  let match: RegExpExecArray | null;
  while ((match = trackRegex.exec(xml)) !== null) {
    const tag = match[0];
    const langMatch = tag.match(/lang_code="([^"]+)"/);
    const nameMatch = tag.match(/name="([^"]*)"/);
    const kindMatch = tag.match(/kind="([^"]*)"/);
    const lang = langMatch ? langMatch[1].trim().toLowerCase() : "";
    if (!lang) continue;
    const label = nameMatch ? clientDecodeEntities(nameMatch[1]).trim() : clientLanguageLabel(lang);
    const kind = kindMatch ? kindMatch[1].trim().toLowerCase() : "";
    const autoGenerated = kind === "asr";
    const key = `${lang}|${autoGenerated ? "asr" : "manual"}`;
    if (seen.has(key)) continue;
    seen.add(key);
    const baseUrl = `https://www.youtube.com/api/timedtext?lang=${encodeURIComponent(lang)}&v=${encodeURIComponent(videoId)}`;
    tracks.push({ baseUrl, language: lang, label: label || clientLanguageLabel(lang), autoGenerated });
  }
  return tracks.length ? tracks : null;
}

async function clientFetchCues(track: RawTrack, signal?: AbortSignal): Promise<RawCue[]> {
  const headers = { "accept-language": "en-US,en;q=0.9" };
  const json3Url = `${track.baseUrl}${track.baseUrl.includes("?") ? "&" : "?"}fmt=json3`;
  try {
    const res = await fetch(json3Url, { signal, headers, credentials: "omit" });
    if (res.status === 429) throw new TranscriptRequestError("too_many_requests");
    if (res.ok) {
      const body = await res.text();
      if (/not a bot|sign in to confirm|g-recaptcha|unusual traffic/i.test(body)) {
        throw new TranscriptRequestError("too_many_requests");
      }
      if (body.trim().startsWith("{")) {
        const cues = clientParseJson3(body);
        if (cues.length) return cues;
      }
      const xmlCues = clientParseXml(body);
      if (xmlCues.length) return xmlCues;
    }
  } catch (error) {
    if (error instanceof TranscriptRequestError) throw error;
    // fall through to plain XML
  }
  const res = await fetch(track.baseUrl, { signal, headers, credentials: "omit" });
  if (res.status === 429) throw new TranscriptRequestError("too_many_requests");
  if (!res.ok) throw new TranscriptRequestError("no_transcript");
  const body = await res.text();
  if (/not a bot|sign in to confirm|g-recaptcha|unusual traffic/i.test(body)) {
    throw new TranscriptRequestError("too_many_requests");
  }
  const cues = clientParseXml(body);
  if (!cues.length) throw new TranscriptRequestError("no_transcript");
  return cues;
}

async function fetchDirectFromYouTube(
  videoId: string,
  language?: string | null,
  signal?: AbortSignal,
): Promise<TranscriptData> {
  const tracks = await clientFetchTimedTextList(videoId, signal);
  if (!tracks || !tracks.length) throw new TranscriptRequestError("no_captions");
  const chosen = clientChooseTrack(tracks, language || undefined);
  if (!chosen) throw new TranscriptRequestError("no_captions");
  const cues = await clientFetchCues(chosen, signal);
  if (!cues.length) throw new TranscriptRequestError("no_transcript");
  const allSegments = clientGroupCues(cues);
  if (!allSegments.length) throw new TranscriptRequestError("no_transcript");
  const MAX_SEGMENTS = 4000;
  const truncated = allSegments.length > MAX_SEGMENTS;
  const segments = truncated ? allSegments.slice(0, MAX_SEGMENTS) : allSegments;
  return {
    videoId,
    title: "",
    language: chosen.language,
    languageLabel: chosen.label || clientLanguageLabel(chosen.language),
    autoGenerated: chosen.autoGenerated,
    tracks: tracks.map((t) => ({
      language: t.language,
      label: t.label || clientLanguageLabel(t.language),
      autoGenerated: t.autoGenerated,
    })),
    segments,
    truncated,
    fetchedAt: Date.now(),
  };
}

/**
 * Fetch one video's transcript. Throws `TranscriptRequestError` with the
 * server's code (or `service_unavailable` when the API path is not hosted),
 * and never caches a failure.
 */
export async function loadYouTubeTranscript(
  videoId: string,
  language?: string | null,
  signal?: AbortSignal,
): Promise<TranscriptData> {
  const id = String(videoId || "").trim();
  if (!/^[A-Za-z0-9_-]{11}$/.test(id)) {
    throw new TranscriptRequestError("bad_video");
  }
  const lang = String(language || "").trim().toLowerCase();
  const key = cacheKeyFor(id, lang);
  const cached = transcriptCache.get(key);
  if (cached) return cached;

  // 1. Try the server first — it is cached at CDN and works for most videos
  const search = new URLSearchParams({ v: id });
  if (lang) search.set("lang", lang);
  let serverFailedWithRetryable = false;
  let serverError: TranscriptRequestError | null = null;

  try {
    let response: Response;
    try {
      response = await apiFetch(`/api/youtube-transcript?${search.toString()}`, { signal, headers: { accept: "application/json" } });
    } catch (error) {
      if ((error as { name?: string })?.name === "AbortError") {
        throw new TranscriptRequestError("aborted");
      }
      throw new TranscriptRequestError("network");
    }

    let payload: unknown = null;
    try {
      payload = await response.json();
    } catch {
      // A static host / missing rewrite answers the SPA's HTML with HTTP 200.
      throw new TranscriptRequestError("service_unavailable");
    }
    const record = (payload && typeof payload === "object" ? payload : {}) as Record<string, unknown>;
    if (!response.ok || record.ok === false) {
      const rawCode = String(record.code || "").trim();
      const code = (rawCode in TRANSCRIPT_ERROR_COPY ? rawCode : "fetch_failed") as TranscriptClientErrorCode;
      const rawMessage = String(record.error || "").trim();
      const looksLikeBotMessage = /not a bot|sign in to confirm|unusual traffic|g-recaptcha|confirm you.*bot/i.test(rawMessage);
      const shouldUseCopy =
        !rawMessage ||
        looksLikeBotMessage ||
        code === "too_many_requests" ||
        code === "video_unavailable" ||
        code === "service_unavailable";
      const message = shouldUseCopy ? TRANSCRIPT_ERROR_COPY[code] : rawMessage;
      throw new TranscriptRequestError(code, message);
    }
    const segments = Array.isArray(record.segments)
      ? (record.segments as unknown[])
          .map((item) => {
            const segment = (item && typeof item === "object" ? item : {}) as Record<string, unknown>;
            const start = Number(segment.start);
            const duration = Number(segment.duration);
            const text = String(segment.text || "").trim();
            if (!text || !Number.isFinite(start)) return null;
            return { start: Math.max(0, start), duration: Number.isFinite(duration) ? Math.max(0, duration) : 0, text };
          })
          .filter((segment): segment is TranscriptSegment => Boolean(segment))
      : [];
    if (!segments.length) throw new TranscriptRequestError("no_transcript");

    const data: TranscriptData = {
      videoId: String(record.videoId || id),
      title: String(record.title || "").trim(),
      language: String(record.language || lang || "").trim(),
      languageLabel: String(record.languageLabel || "").trim() || "Transcript",
      autoGenerated: Boolean(record.autoGenerated),
      tracks: Array.isArray(record.tracks)
        ? (record.tracks as unknown[])
            .map((item) => {
              const track = (item && typeof item === "object" ? item : {}) as Record<string, unknown>;
              const code = String(track.language || "").trim().toLowerCase();
              if (!code) return null;
              return {
                language: code,
                label: String(track.label || code).trim(),
                autoGenerated: Boolean(track.autoGenerated),
              };
            })
            .filter((track): track is TranscriptTrackInfo => Boolean(track))
        : [],
      segments,
      truncated: Boolean(record.truncated),
      fetchedAt: Number(record.fetchedAt) || Date.now(),
    };
    rememberTranscript(key, data);
    return data;
  } catch (error) {
    if (error instanceof TranscriptRequestError) {
      // These codes are worth a direct-browser fallback — the server IP is
      // blocked, but the learner's own IP usually is not.
      if (
        error.code === "too_many_requests" ||
        error.code === "fetch_failed" ||
        error.code === "service_unavailable" ||
        error.code === "timeout" ||
        error.code === "network"
      ) {
        serverFailedWithRetryable = true;
        serverError = error;
      } else {
        throw error;
      }
    } else {
      serverFailedWithRetryable = true;
      serverError = new TranscriptRequestError("fetch_failed");
    }
  }

  // 2. Server was rate-limited / unreachable — try direct from this browser
  // (user's own IP). This is what makes APK / PWA work even when Vercel's
  // IP is flagged by YouTube.
  if (serverFailedWithRetryable) {
    try {
      const direct = await fetchDirectFromYouTube(id, lang || null, signal);
      rememberTranscript(key, direct);
      return direct;
    } catch (fallbackError) {
      // If fallback also says too_many_requests, keep the server's friendly
      // copy — it already explains the situation. If fallback says no_captions,
      // that is more specific than the server's generic failure.
      if (fallbackError instanceof TranscriptRequestError) {
        if (fallbackError.code === "no_captions" || fallbackError.code === "no_transcript") {
          throw fallbackError;
        }
        if (fallbackError.code === "too_many_requests" && serverError) {
          throw serverError;
        }
      }
      if (serverError) throw serverError;
      throw fallbackError;
    }
  }

  throw serverError || new TranscriptRequestError("fetch_failed");
}
