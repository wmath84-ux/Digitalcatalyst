export type TranscriptSegment = {
  start: number;
  duration: number;
  text: string;
};

export type TranscriptTrackInfo = {
  language: string;
  label: string;
  autoGenerated: boolean;
};

/** One layer's answer — the evidence the page's "Details" disclosure shows. */
export type TranscriptAttempt = {
  source: string;
  answered?: boolean;
  tracks?: number;
  playability?: string;
  blocked?: boolean;
  note?: string;
};

export type TranscriptData = {
  videoId: string;
  title: string;
  language: string;
  languageLabel: string;
  autoGenerated: boolean;
  tracks: TranscriptTrackInfo[];
  segments: TranscriptSegment[];
  truncated: boolean;
  fetchedAt: number;
  /** Which layer produced the lines ("caption-track(hi)", "browser:panel"…). */
  strategy?: string;
  /** Every layer that was tried, in order. */
  attempts?: TranscriptAttempt[];
};

export type TranscriptClientErrorCode =
  | "bad_video"
  | "video_unavailable"
  | "no_captions"
  | "no_transcript"
  | "too_many_requests"
  | "timeout"
  | "fetch_failed"
  | "service_unavailable"
  | "network"
  | "aborted";

export class TranscriptRequestError extends Error {
  code: TranscriptClientErrorCode;
  /** What each layer said — server-side first, then this browser's own tries. */
  attempts: TranscriptAttempt[];

  constructor(code: TranscriptClientErrorCode, message?: string, attempts?: TranscriptAttempt[]) {
    super(message || code);
    this.name = "TranscriptRequestError";
    this.code = code;
    this.attempts = Array.isArray(attempts) ? attempts : [];
  }
}

