const transcriptCache = new Map<string, TranscriptData>();
const CACHE_LIMIT = 24;

/**
 * Videos whose "no captions" verdict has already been double-checked from this
 * browser. A server that says a video has no captions is usually right, and the
 * browser's second opinion costs three requests — so it is spent once per
 * video per session, not once per retry.
 */
const browserSecondOpinionUsed = new Set<string>();

const cacheKeyFor = (videoId: string, language?: string | null) =>
  `${videoId}|${String(language || "").trim().toLowerCase() || "auto"}`;

/** Remember a transcript for the rest of this session (and keep the map small). */
function rememberTranscript(key: string, data: TranscriptData) {
  transcriptCache.delete(key);
  transcriptCache.set(key, data);
  while (transcriptCache.size > CACHE_LIMIT) {
    const oldest = transcriptCache.keys().next().value;
    if (oldest === undefined) break;
    transcriptCache.delete(oldest);
  }
}

/**
 * Drop a cached answer (the page's Retry button uses this) — and with it the
 * "already double-checked from this browser" mark, so a deliberate retry really
 * does run every path again.
 */
export function forgetTranscript(videoId: string, language?: string | null) {
  const key = cacheKeyFor(videoId, language);
  transcriptCache.delete(key);
  browserSecondOpinionUsed.delete(key);
}

/**
 * The video id of the file currently open in the lesson pane, or "" when the
 * open resource is not a YouTube video.
 */
export function youTubeVideoIdForFile(file: CourseFile | null | undefined): string {
  if (!file) return "";
  const direct = String((file as CourseFile & { youtubeVideoId?: string }).youtubeVideoId || "").trim();
  if (/^[A-Za-z0-9_-]{11}$/.test(direct)) return direct;
  const raw = getCourseFileUrl(file);
  const fromUrl = extractYouTubeId(raw);
  if (/^[A-Za-z0-9_-]{11}$/.test(fromUrl)) return fromUrl;
  // `extractYouTubeId` covers watch / youtu.be / shorts / embed; the player
  // also accepts a live URL, and a pasted watch link can carry the id in its
  // path. Keep the page honest for those shapes too.
  const match = String(raw || "").match(/(?:v=|youtu\.be\/|embed\/|shorts\/|live\/)([A-Za-z0-9_-]{11})/);
  return match ? match[1] : "";
}

/** `4:07` for short videos, `1:04:07` once the hour rolls over. */
export function transcriptTimestamp(totalSeconds: number): string {
  const safe = Math.max(0, Math.floor(Number(totalSeconds) || 0));
  const hours = Math.floor(safe / 3600);
  const minutes = Math.floor((safe % 3600) / 60);
  const seconds = safe % 60;
  const pad = (value: number) => String(value).padStart(2, "0");
  return hours > 0 ? `${hours}:${pad(minutes)}:${pad(seconds)}` : `${minutes}:${pad(seconds)}`;
}

/**
 * The index of the line that contains `position`, via binary search. A line
 * stays active until the next one starts; before the first line, line 0.
 */
export function activeTranscriptIndex(segments: TranscriptSegment[], position: number): number {
  if (!segments.length) return -1;
  const at = Math.max(0, Number(position) || 0);
  let low = 0;
  let high = segments.length - 1;
  let answer = 0;
  while (low <= high) {
    const mid = (low + high) >> 1;
    if (segments[mid].start <= at + 0.05) {
      answer = mid;
      low = mid + 1;
    } else {
      high = mid - 1;
    }
  }
  return answer;
}

/* ── Client-side direct YouTube fallback (bypasses server IP block) ────────
   When the server is rate-limited (YouTube bot check from Vercel's IP), the
   learner's own browser IP is usually NOT blocked. So we try the legacy
   timedtext endpoints directly from the browser:

     1. GET https://www.youtube.com/api/timedtext?type=list&v=ID
        → XML list of caption tracks
     2. GET https://www.youtube.com/api/timedtext?lang=CODE&v=ID&fmt=json3
        → JSON3 cues, fallback to XML

   This is the same pipeline the server uses, but executed with the user's IP.
   If CORS blocks it (some browsers / some regions), we fail gracefully and
   the server's friendly error is what the page shows — with a retry + open
   on YouTube CTA.
*/

type RawCue = { start: number; end: number; text: string };
type RawTrack = { baseUrl: string; language: string; label: string; autoGenerated: boolean };

function clientDecodeEntities(text: string): string {
  const once = String(text || "")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&apos;/g, "'")
    .replace(/&nbsp;/g, " ")
    .replace(/&#x([0-9a-fA-F]+);/g, (_, hex: string) => String.fromCodePoint(parseInt(hex, 16)))
    .replace(/&#(\d+);/g, (_, dec: string) => String.fromCodePoint(parseInt(dec, 10)));
  return once.includes("&amp;") ? clientDecodeEntities(once) : once;
}

function clientCleanCueText(text: string): string {
  return clientDecodeEntities(text)
    .replace(/<[^>]*>/g, " ")
    .replace(/\u200b/g, "")
    .replace(/\s+/g, " ")
    .replace(/^(?:>>\s*)+/, "")
    .trim();
}

function clientParseJson3(raw: string): RawCue[] {
  let data: unknown;
  try {
    data = JSON.parse(raw);
  } catch {
    return [];
  }
  const events = (data && typeof data === "object" ? (data as { events?: unknown }).events : null);
  if (!Array.isArray(events)) return [];
  const cues: RawCue[] = [];
  for (const event of events) {
    if (!event || typeof event !== "object") continue;
    const record = event as Record<string, unknown>;
    const segs = Array.isArray(record.segs) ? record.segs : [];
    const text = clientCleanCueText(
      segs
        .map((seg) => (seg && typeof seg === "object" ? String((seg as { utf8?: unknown }).utf8 || "") : ""))
        .join(""),
    );
    if (!text) continue;
    const start = Math.max(0, Number(record.tStartMs || 0) / 1000);
    const duration = Math.max(0, Number(record.dDurationMs || 0) / 1000);
    cues.push({ start, end: start + duration, text });
  }
  return cues;
}

function clientParseXml(raw: string): RawCue[] {
  const xml = String(raw || "");
  const cues: RawCue[] = [];
  const paragraph = /<p\s+t="(\d+)"(?:\s+d="(\d+)")?[^>]*>([\s\S]*?)<\/p>/g;
  let match: RegExpExecArray | null;
  while ((match = paragraph.exec(xml)) !== null) {
    const inner = match[3] || "";
    const words: string[] = [];
    const wordRegex = /<s[^>]*>([\s\S]*?)<\/s>/g;
    let wordMatch: RegExpExecArray | null;
    while ((wordMatch = wordRegex.exec(inner)) !== null) words.push(wordMatch[1]);
    const text = clientCleanCueText(words.length ? words.join("") : inner.replace(/<[^>]*>/g, ""));
    if (!text) continue;
    const start = Math.max(0, Number(match[1]) / 1000);
    const duration = Math.max(0, Number(match[2] || 0) / 1000);
    cues.push({ start, end: start + duration, text });
  }
  if (cues.length) return cues;
  const classic = /<text\s+start="([^"]*)"(?:\s+dur="([^"]*)")?[^>]*>([\s\S]*?)<\/text>/g;
  while ((match = classic.exec(xml)) !== null) {
    const text = clientCleanCueText(match[3]);
    if (!text) continue;
    const start = Math.max(0, Number(match[1]) || 0);
    const duration = Math.max(0, Number(match[2]) || 0);
    cues.push({ start, end: start + duration, text });
  }
  return cues;
}

function clientGroupCues(cues: RawCue[]): TranscriptSegment[] {
  const segments: TranscriptSegment[] = [];
  let current: RawCue | null = null;
  const flush = () => {
    if (!current) return;
    const text = current.text.replace(/\s+/g, " ").trim();
    if (text) {
      segments.push({
        start: Math.round(current.start * 1000) / 1000,
        duration: Math.max(0, Math.round((current.end - current.start) * 1000) / 1000),
        text,
      });
    }
    current = null;
  };
  for (const cue of cues) {
    if (!cue.text) continue;
    if (!current) {
      current = { ...cue };
      continue;
    }
    const gap = cue.start - current.end;
    const sentenceEnded = /[.!?।]$/.test(current.text);
    const tooLong = cue.end - current.start > 14 || current.text.length + cue.text.length > 280;
    if (gap > 1.5 || (sentenceEnded && current.text.length >= 55) || tooLong) {
      flush();
      current = { ...cue };
      continue;
    }
    current.text = `${current.text} ${cue.text}`.replace(/\s+/g, " ").trim();
    current.end = Math.max(current.end, cue.end);
  }
  flush();
  return segments;
}

function clientChooseTrack(tracks: RawTrack[], requested?: string): RawTrack | null {
  if (!tracks.length) return null;
  const lang = String(requested || "").trim().toLowerCase();
  if (lang) {
    const exact = tracks.find((t) => t.language === lang);
    if (exact) return exact;
    const prefix = tracks.find((t) => t.language.startsWith(`${lang}-`) || lang.startsWith(`${t.language}-`));
    if (prefix) return prefix;
  }
  const manual = tracks.filter((t) => !t.autoGenerated);
  const auto = tracks.filter((t) => t.autoGenerated);
  return (
    manual.find((t) => t.language === "en" || t.language.startsWith("en-")) ||
    manual[0] ||
    auto.find((t) => t.language === "en" || t.language.startsWith("en-")) ||
    auto[0] ||
    tracks[0]
  );
}

function clientLanguageLabel(code: string): string {
  const clean = String(code || "").trim();
  if (!clean) return "Unknown";
  try {
    const names = new Intl.DisplayNames(["en"], { type: "language" });
    const label = names.of(clean) || names.of(clean.split("-")[0]) || "";
    if (label) return label;
  } catch {
    /* no Intl.DisplayNames */
  }
  const base = clean.split("-")[0];
  const fallback: Record<string, string> = {
    en: "English", hi: "Hindi", ur: "Urdu", es: "Spanish", fr: "French",
    de: "German", pt: "Portuguese", ar: "Arabic", zh: "Chinese", ja: "Japanese",
    ko: "Korean", ru: "Russian", bn: "Bengali", ta: "Tamil", te: "Telugu",
    mr: "Marathi", gu: "Gujarati", kn: "Kannada", ml: "Malayalam", pa: "Punjabi",
    id: "Indonesian", tr: "Turkish", vi: "Vietnamese", th: "Thai", it: "Italian",
  };
  return fallback[base] || clean;
}

async function clientFetchTimedTextList(videoId: string, signal?: AbortSignal): Promise<RawTrack[] | null> {
  const url = `https://www.youtube.com/api/timedtext?type=list&v=${encodeURIComponent(videoId)}&hl=en`;
  let response: Response;
  try {
    response = await fetch(url, { signal, credentials: "omit" });
  } catch {
    return null; // CORS or network — let server error be the final answer
  }
  if (response.status === 429) throw new TranscriptRequestError("too_many_requests");
  if (!response.ok) return null;
  let xml = "";
  try {
    xml = await response.text();
  } catch {
    return null;
  }
  if (/not a bot|sign in to confirm|g-recaptcha|unusual traffic/i.test(xml)) {
    throw new TranscriptRequestError("too_many_requests");
  }
  const tracks: RawTrack[] = [];
  const seen = new Set<string>();
  const trackRegex = /<track[^>]+>/g;
  let match: RegExpExecArray | null;
  while ((match = trackRegex.exec(xml)) !== null) {
    const tag = match[0];
    const langMatch = tag.match(/lang_code="([^"]+)"/);
    const nameMatch = tag.match(/name="([^"]*)"/);
    const kindMatch = tag.match(/kind="([^"]*)"/);
    const lang = langMatch ? langMatch[1].trim().toLowerCase() : "";
    if (!lang) continue;
    const label = nameMatch ? clientDecodeEntities(nameMatch[1]).trim() : clientLanguageLabel(lang);
    const kind = kindMatch ? kindMatch[1].trim().toLowerCase() : "";
    const autoGenerated = kind === "asr";
    const key = `${lang}|${autoGenerated ? "asr" : "manual"}`;
    if (seen.has(key)) continue;
    seen.add(key);
    const baseUrl = `https://www.youtube.com/api/timedtext?lang=${encodeURIComponent(lang)}&v=${encodeURIComponent(videoId)}`;
    tracks.push({ baseUrl, language: lang, label: label || clientLanguageLabel(lang), autoGenerated });
  }
  return tracks.length ? tracks : null;
}

async function clientFetchCues(track: RawTrack, signal?: AbortSignal): Promise<RawCue[]> {
  const headers = { "accept-language": "en-US,en;q=0.9" };
  const json3Url = `${track.baseUrl}${track.baseUrl.includes("?") ? "&" : "?"}fmt=json3`;
  try {
    const res = await fetch(json3Url, { signal, headers, credentials: "omit" });
    if (res.status === 429) throw new TranscriptRequestError("too_many_requests");
    if (res.ok) {
      const body = await res.text();
      if (/not a bot|sign in to confirm|g-recaptcha|unusual traffic/i.test(body)) {
        throw new TranscriptRequestError("too_many_requests");
      }
      if (body.trim().startsWith("{")) {
        const cues = clientParseJson3(body);
        if (cues.length) return cues;
      }
      const xmlCues = clientParseXml(body);
      if (xmlCues.length) return xmlCues;
    }
  } catch (error) {
    if (error instanceof TranscriptRequestError) throw error;
    // fall through to plain XML
  }
  const res = await fetch(track.baseUrl, { signal, headers, credentials: "omit" });
  if (res.status === 429) throw new TranscriptRequestError("too_many_requests");
  if (!res.ok) throw new TranscriptRequestError("no_transcript");
  const body = await res.text();
  if (/not a bot|sign in to confirm|g-recaptcha|unusual traffic/i.test(body)) {
    throw new TranscriptRequestError("too_many_requests");
  }
  const cues = clientParseXml(body);
  if (!cues.length) throw new TranscriptRequestError("no_transcript");
  return cues;
}

/* ── The browser's own InnerTube attempts ──────────────────────────────────
   Two more ways to read a transcript without the server, both from the
   learner's own IP:

     1. `youtubei/v1/player` — the caption track list, exactly as the server
        asks for it. A track's `baseUrl` is then fetched for the lines.
     2. `youtubei/v1/get_transcript` — YouTube's own "Show transcript" panel.
        It answers with the LINES themselves (start, end, text), so there is no
        signed URL to expire and nothing to re-negotiate.

   Both are POSTs to youtube.com from a page that is not youtube.com, so a
   browser may refuse them on CORS. That is not an error worth showing: each
   attempt is recorded and the next one is tried. Inside the installed app the
   WebView is often more permissive, and the residential IP is the point — it
   is not on YouTube's datacentre blocklist. */

const CLIENT_INNERTUBE_PLAYER_URL = "https://www.youtube.com/youtubei/v1/player?prettyPrint=false";
const CLIENT_INNERTUBE_TRANSCRIPT_URL = "https://www.youtube.com/youtubei/v1/get_transcript?prettyPrint=false";
const CLIENT_WEB_VERSION = "2.20250222.10.00";

/** `params` for get_transcript: protobuf field 1 + length + the video id. */
function clientTranscriptParams(videoId: string): string {
  const id = String(videoId || "").trim();
  if (!/^[A-Za-z0-9_-]{11}$/.test(id)) return "";
  const bytes = [0x0a, id.length];
  for (let index = 0; index < id.length; index += 1) bytes.push(id.charCodeAt(index) & 0xff);
  const ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
  let out = "";
  for (let index = 0; index < bytes.length; index += 3) {
    const chunk = [bytes[index], bytes[index + 1], bytes[index + 2]];
    const have = chunk.filter((value) => value !== undefined).length;
    const value = ((chunk[0] || 0) << 16) | ((chunk[1] || 0) << 8) | (chunk[2] || 0);
    out += ALPHABET[(value >> 18) & 63] + ALPHABET[(value >> 12) & 63];
    out += have > 1 ? ALPHABET[(value >> 6) & 63] : "=";
    out += have > 2 ? ALPHABET[value & 63] : "=";
  }
  return out;
}

/** Read `{ simpleText }` / `{ runs: [{ text }] }` — YouTube's own two shapes. */
function clientReadText(value: unknown): string {
  if (typeof value === "string") return value.trim();
  if (!value || typeof value !== "object") return "";
  const record = value as Record<string, unknown>;
  if (typeof record.simpleText === "string") return record.simpleText.trim();
  if (Array.isArray(record.runs)) {
    return record.runs
      .map((run) => (run && typeof run === "object" ? String((run as Record<string, unknown>).text || "") : ""))
      .join("")
      .trim();
  }
  return "";
}

/**
 * Lift the panel's segments out of the answer with a recursive walk: a segment
 * is simply the object carrying `startMs` together with a `snippet`. YouTube
 * re-shapes this renderer often, and a walk survives that.
 */
function clientCollectPanelCues(node: unknown, out: RawCue[] = []): RawCue[] {
  if (!node || typeof node !== "object") return out;
  if (Array.isArray(node)) {
    for (const item of node) clientCollectPanelCues(item, out);
    return out;
  }
  const record = node as Record<string, unknown>;
  const startRaw = record.startMs;
  if ((typeof startRaw === "string" || typeof startRaw === "number") && record.snippet) {
    const text = clientCleanCueText(clientReadText(record.snippet));
    if (text) {
      const start = Math.max(0, Number(startRaw) / 1000);
      const end = Math.max(start, Number(record.endMs ?? 0) / 1000);
      out.push({ start, end, text });
    }
  }
  for (const value of Object.values(record)) clientCollectPanelCues(value, out);
  return out;
}

/** "English (auto-generated)" → { code: "en", label, autoGenerated }. */
function clientPanelLanguage(json: unknown): { language: string; label: string; autoGenerated: boolean } {
  let footer = "";
  const walk = (node: unknown, depth = 0): void => {
    if (footer || !node || typeof node !== "object" || depth > 24) return;
    if (Array.isArray(node)) {
      for (const item of node) walk(item, depth + 1);
      return;
    }
    const record = node as Record<string, unknown>;
    if (record.transcriptFooterRenderer && typeof record.transcriptFooterRenderer === "object") {
      const text = clientReadText((record.transcriptFooterRenderer as Record<string, unknown>).initialDescription);
      if (text) {
        footer = text;
        return;
      }
    }
    for (const value of Object.values(record)) walk(value, depth + 1);
  };
  walk(json);
  const autoGenerated = /auto[- ]?generated/i.test(footer);
  const label = footer.replace(/\s*\((?:auto[- ]?generated|generated)\)\s*/i, "").trim();
  const lower = label.toLowerCase();
  const codes = ["en", "hi", "ur", "es", "fr", "de", "pt", "ar", "bn", "ta", "te", "mr", "gu", "kn", "ml", "pa", "id", "zh", "ja", "ko", "ru"];
  let language = /^[a-z]{2,3}(?:-[a-z0-9]{2,8})?$/i.test(lower) ? lower : "";
  if (!language) {
    for (const code of codes) {
      if (clientLanguageLabel(code).toLowerCase() === lower) {
        language = code;
        break;
      }
    }
  }
  return { language, label: label || (language ? clientLanguageLabel(language) : "Transcript"), autoGenerated };
}

async function clientPostInnerTube(url: string, body: unknown, signal?: AbortSignal): Promise<unknown | null> {
  try {
    const response = await fetch(url, {
      method: "POST",
      signal,
      credentials: "omit",
      headers: { "content-type": "application/json", "accept-language": "en-US,en;q=0.9" },
      body: JSON.stringify(body),
    });
    if (response.status === 429) throw new TranscriptRequestError("too_many_requests");
    if (!response.ok) return null;
    return await response.json();
  } catch (error) {
    if (error instanceof TranscriptRequestError) throw error;
    // A CORS refusal or a network drop is simply "this path is closed here".
    return null;
  }
}

/** Strategy 1: the player API's caption list, then the track's own URL. */
async function clientFetchViaInnerTube(
  videoId: string,
  language?: string | null,
  signal?: AbortSignal,
): Promise<{ data: TranscriptData | null; attempts: TranscriptAttempt[] }> {
  const attempts: TranscriptAttempt[] = [];
  const clients: Array<{ name: string; clientName: string; version: string }> = [
    { name: "WEB", clientName: "WEB", version: CLIENT_WEB_VERSION },
    { name: "ANDROID", clientName: "ANDROID", version: "20.10.38" },
    { name: "TVHTML5_SIMPLY_EMBEDDED_PLAYER", clientName: "TVHTML5_SIMPLY_EMBEDDED_PLAYER", version: "2.0" },
  ];
  for (const client of clients) {
    const body: Record<string, unknown> = {
      context: { client: { clientName: client.clientName, clientVersion: client.version, hl: "en", gl: "US" } },
      videoId,
      contentCheckOk: true,
      racyCheckOk: true,
    };
    if (client.clientName === "TVHTML5_SIMPLY_EMBEDDED_PLAYER") {
      body.params = "CgIQBg==";
      body.thirdParty = { embedUrl: "https://www.youtube.com/" };
    }
    const json = await clientPostInnerTube(CLIENT_INNERTUBE_PLAYER_URL, body, signal);
    if (!json || typeof json !== "object") {
      attempts.push({ source: `browser:innertube:${client.name}`, answered: false, note: "no answer (CORS or blocked)" });
      continue;
    }
    const record = json as Record<string, unknown>;
    const captions = (record.captions || {}) as Record<string, unknown>;
    const renderer = (captions.playerCaptionsTracklistRenderer || {}) as Record<string, unknown>;
    const list = Array.isArray(renderer.captionTracks) ? (renderer.captionTracks as Array<Record<string, unknown>>) : [];
    const tracks: RawTrack[] = list
      .map((track) => ({
        baseUrl: String(track?.baseUrl || "").trim(),
        language: String(track?.languageCode || "").trim().toLowerCase(),
        label: clientReadText(track?.name) || clientLanguageLabel(String(track?.languageCode || "")),
        autoGenerated: String(track?.kind || "").toLowerCase() === "asr",
      }))
      .filter((track) => track.baseUrl && track.language && /^https:\/\/([a-z0-9-]+\.)*youtube(-nocookie)?\.com\//i.test(track.baseUrl));
    const details = (record.videoDetails || {}) as Record<string, unknown>;
    const playability = (record.playabilityStatus || {}) as Record<string, unknown>;
    if (!tracks.length) {
      attempts.push({
        source: `browser:innertube:${client.name}`,
        answered: true,
        tracks: 0,
        playability: String(playability.status || ""),
        note: String(playability.reason || "no caption tracks in this answer"),
      });
      continue;
    }
    const chosen = clientChooseTrack(tracks, language || undefined);
    if (!chosen) continue;
    attempts.push({ source: `browser:innertube:${client.name}`, answered: true, tracks: tracks.length, note: `track ${chosen.language}` });
    try {
      // A track minted for one client is refused by another's User-Agent; the
      // browser cannot set that header, so the plain URL is what we ask for.
      const cues = await clientFetchCues(chosen, signal);
      if (!cues.length) continue;
      const data = buildClientTranscript(videoId, String(details.title || "").trim(), chosen, tracks, cues, `browser:innertube(${client.name})`, attempts);
      if (data) return { data, attempts };
    } catch (error) {
      if (error instanceof TranscriptRequestError && error.code === "too_many_requests") throw error;
      attempts.push({ source: `browser:caption-download:${client.name}`, answered: false, note: error instanceof Error ? error.message : "download failed" });
    }
  }
  return { data: null, attempts };
}

/** Strategy 2: YouTube's own transcript panel — lines, no signed URL. */
async function clientFetchViaPanel(
  videoId: string,
  signal?: AbortSignal,
): Promise<{ data: TranscriptData | null; attempts: TranscriptAttempt[] }> {
  const attempts: TranscriptAttempt[] = [];
  const params = clientTranscriptParams(videoId);
  if (!params) return { data: null, attempts };
  const json = await clientPostInnerTube(
    CLIENT_INNERTUBE_TRANSCRIPT_URL,
    { context: { client: { clientName: "WEB", clientVersion: CLIENT_WEB_VERSION, hl: "en", gl: "US" } }, params },
    signal,
  );
  if (!json) {
    attempts.push({ source: "browser:get_transcript", answered: false, note: "no answer (CORS or blocked)" });
    return { data: null, attempts };
  }
  const cues = clientCollectPanelCues(json);
  if (!cues.length) {
    attempts.push({ source: "browser:get_transcript", answered: true, tracks: 0, note: "panel answered with no segments" });
    return { data: null, attempts };
  }
  const { language, label, autoGenerated } = clientPanelLanguage(json);
  attempts.push({ source: "browser:get_transcript", answered: true, tracks: 1, note: `${cues.length} segments (${label})` });
  const track: RawTrack = { baseUrl: "", language: language || "und", label, autoGenerated };
  const data = buildClientTranscript(videoId, "", track, [track], cues, "browser:get_transcript", attempts);
  return { data, attempts };
}

/** Group the cues and shape the page's own TranscriptData. */
function buildClientTranscript(
  videoId: string,
  title: string,
  chosen: RawTrack,
  tracks: RawTrack[],
  cues: RawCue[],
  strategy: string,
  attempts: TranscriptAttempt[],
): TranscriptData | null {
  const allSegments = clientGroupCues(cues);
  if (!allSegments.length) return null;
  const MAX_SEGMENTS = 4000;
  const truncated = allSegments.length > MAX_SEGMENTS;
  return {
    videoId,
    title,
    language: chosen.language,
    languageLabel: chosen.label || clientLanguageLabel(chosen.language),
    autoGenerated: chosen.autoGenerated,
    tracks: tracks.map((track) => ({
      language: track.language,
      label: track.label || clientLanguageLabel(track.language),
      autoGenerated: track.autoGenerated,
    })),
    segments: truncated ? allSegments.slice(0, MAX_SEGMENTS) : allSegments,
    truncated,
    fetchedAt: Date.now(),
    strategy,
    attempts,
  };
}

/** Strategy 3: the legacy timedtext list (the browser's oldest door). */
async function clientFetchViaTimedText(
  videoId: string,
  language?: string | null,
  signal?: AbortSignal,
): Promise<{ data: TranscriptData | null; attempts: TranscriptAttempt[] }> {
  const attempts: TranscriptAttempt[] = [];
  const tracks = await clientFetchTimedTextList(videoId, signal);
  if (!tracks || !tracks.length) {
    attempts.push({ source: "browser:timedtext-list", answered: false, note: "empty or blocked (CORS)" });
    return { data: null, attempts };
  }
  const chosen = clientChooseTrack(tracks, language || undefined);
  if (!chosen) return { data: null, attempts };
  attempts.push({ source: "browser:timedtext-list", answered: true, tracks: tracks.length, note: `track ${chosen.language}` });
  const cues = await clientFetchCues(chosen, signal);
  if (!cues.length) return { data: null, attempts };
  const data = buildClientTranscript(videoId, "", chosen, tracks, cues, "browser:timedtext", attempts);
  return { data, attempts };
}

/**
 * The browser's own attempt at the transcript, with the learner's own IP.
 * Every strategy is tried in order; the first one that produces lines wins.
 * The `attempts` it reports are what the page shows under "Details".
 */
/**
 * The whole browser-side second opinion is budgeted. A learner who is offline,
 * or behind a network that closes these doors, must not stare at a skeleton for
 * thirty seconds before the page admits defeat — after this long the remaining
 * strategies are skipped and the server's verdict is shown.
 */
const BROWSER_BUDGET_MS = 9_000;

async function fetchDirectFromYouTube(
  videoId: string,
  language?: string | null,
  signal?: AbortSignal,
): Promise<{ data: TranscriptData; attempts: TranscriptAttempt[] }> {
  const attempts: TranscriptAttempt[] = [];
  let blocked = false;

  // One controller for the whole budget, chained to the caller's own signal
  // (the page aborts when the learner switches tabs or videos).
  const controller = new AbortController();
  const budget = setTimeout(() => controller.abort(), BROWSER_BUDGET_MS);
  const onOuterAbort = () => controller.abort();
  signal?.addEventListener?.("abort", onOuterAbort);
  const localSignal = controller.signal;

  const strategies: Array<() => Promise<{ data: TranscriptData | null; attempts: TranscriptAttempt[] }>> = [
    () => clientFetchViaInnerTube(videoId, language, localSignal),
    () => clientFetchViaPanel(videoId, localSignal),
    () => clientFetchViaTimedText(videoId, language, localSignal),
  ];

  try {
    for (const strategy of strategies) {
      if (localSignal.aborted) break;
      let outcome: { data: TranscriptData | null; attempts: TranscriptAttempt[] };
      try {
        outcome = await strategy();
      } catch (error) {
        if (error instanceof TranscriptRequestError && error.code === "too_many_requests") {
          blocked = true;
          attempts.push({ source: "browser", answered: false, blocked: true, note: "YouTube is throttling this network too" });
          continue;
        }
        if (signal?.aborted) throw new TranscriptRequestError("aborted");
        attempts.push({ source: "browser", answered: false, note: error instanceof Error ? error.message : "attempt failed" });
        continue;
      }
      attempts.push(...(outcome.attempts || []));
      if (outcome.data) return { data: outcome.data, attempts };
    }
  } finally {
    clearTimeout(budget);
    signal?.removeEventListener?.("abort", onOuterAbort);
  }

  if (signal?.aborted) throw new TranscriptRequestError("aborted");
  if (localSignal.aborted) {
    attempts.push({ source: "browser", answered: false, note: "the browser attempt ran out of time" });
  }
  throw new TranscriptRequestError(blocked ? "too_many_requests" : "no_captions", undefined, attempts);
}

/**
 * Fetch one video's transcript. Throws `TranscriptRequestError` with the
 * server's code (or `service_unavailable` when the API path is not hosted),
 * and never caches a failure.
 */
export async function loadYouTubeTranscript(
  videoId: string,
  language?: string | null,
  signal?: AbortSignal,
): Promise<TranscriptData> {
  const id = String(videoId || "").trim();
  if (!/^[A-Za-z0-9_-]{11}$/.test(id)) {
    throw new TranscriptRequestError("bad_video");
  }
  const lang = String(language || "").trim().toLowerCase();
  const key = cacheKeyFor(id, lang);
  const cached = transcriptCache.get(key);
  if (cached) return cached;

  const attempts: TranscriptAttempt[] = [];

  // 1. The server first — it is cached at the CDN and answers for most videos.
  //    `diagnostics=1` asks it to report what every layer saw, which is what
  //    makes an honest "Details" line possible on a failure.
  const search = new URLSearchParams({ v: id, diagnostics: "1" });
  if (lang) search.set("lang", lang);
  let serverError: TranscriptRequestError | null = null;

  try {
    let response: Response;
    try {
      response = await apiFetch(`/api/youtube-transcript?${search.toString()}`, { signal, headers: { accept: "application/json" } });
    } catch (error) {
      if ((error as { name?: string })?.name === "AbortError") {
        throw new TranscriptRequestError("aborted");
      }
      throw new TranscriptRequestError("network");
    }

    let payload: unknown = null;
    try {
      payload = await response.json();
    } catch {
      // A static host / missing rewrite answers the SPA's HTML with HTTP 200.
      throw new TranscriptRequestError("service_unavailable");
    }
    const record = (payload && typeof payload === "object" ? payload : {}) as Record<string, unknown>;
    if (Array.isArray(record.attempts)) {
      for (const item of record.attempts) {
        if (item && typeof item === "object") attempts.push(item as TranscriptAttempt);
      }
    }
    if (!response.ok || record.ok === false) {
      const rawCode = String(record.code || "").trim();
      const code = (rawCode in TRANSCRIPT_ERROR_COPY ? rawCode : "fetch_failed") as TranscriptClientErrorCode;
      const rawMessage = String(record.error || "").trim();
      const looksLikeBotMessage = /not a bot|sign in to confirm|unusual traffic|g-recaptcha|confirm you.*bot/i.test(rawMessage);
      const shouldUseCopy =
        !rawMessage ||
        looksLikeBotMessage ||
        code === "too_many_requests" ||
        code === "video_unavailable" ||
        code === "service_unavailable";
      const message = shouldUseCopy ? TRANSCRIPT_ERROR_COPY[code] : rawMessage;
      throw new TranscriptRequestError(code, message, attempts);
    }
    const segments = Array.isArray(record.segments)
      ? (record.segments as unknown[])
          .map((item) => {
            const segment = (item && typeof item === "object" ? item : {}) as Record<string, unknown>;
            const start = Number(segment.start);
            const duration = Number(segment.duration);
            const text = String(segment.text || "").trim();
            if (!text || !Number.isFinite(start)) return null;
            return { start: Math.max(0, start), duration: Number.isFinite(duration) ? Math.max(0, duration) : 0, text };
          })
          .filter((segment): segment is TranscriptSegment => Boolean(segment))
      : [];
    if (!segments.length) throw new TranscriptRequestError("no_transcript", undefined, attempts);

    const data: TranscriptData = {
      videoId: String(record.videoId || id),
      title: String(record.title || "").trim(),
      language: String(record.language || lang || "").trim(),
      languageLabel: String(record.languageLabel || "").trim() || "Transcript",
      autoGenerated: Boolean(record.autoGenerated),
      tracks: Array.isArray(record.tracks)
        ? (record.tracks as unknown[])
            .map((item) => {
              const track = (item && typeof item === "object" ? item : {}) as Record<string, unknown>;
              const code = String(track.language || "").trim().toLowerCase();
              if (!code) return null;
              return {
                language: code,
                label: String(track.label || code).trim(),
                autoGenerated: Boolean(track.autoGenerated),
              };
            })
            .filter((track): track is TranscriptTrackInfo => Boolean(track))
        : [],
      segments,
      truncated: Boolean(record.truncated),
      fetchedAt: Number(record.fetchedAt) || Date.now(),
      strategy: String(record.strategy || "").trim() || undefined,
      attempts,
    };
    rememberTranscript(key, data);
    return data;
  } catch (error) {
    if ((error as { name?: string })?.name === "AbortError") throw new TranscriptRequestError("aborted");
    serverError =
      error instanceof TranscriptRequestError
        ? error
        : new TranscriptRequestError("fetch_failed", undefined, attempts);
    if (!serverError.attempts?.length) serverError.attempts = attempts;
    attempts.push({
      source: "server",
      answered: false,
      blocked: serverError.code === "too_many_requests",
      note: `${serverError.code}: ${serverError.message}`,
    });
  }

  // 2. The browser's own attempt. This is not a rare-path extra: it is the
  //    reason the tab works from a phone at all.
  //
  //    · A throttle / unreachable server is obviously worth retrying from here.
  //    · So is `no_captions` — YouTube strips the caption list from answers it
  //      does not trust, so "no captions" from a datacentre IP is a claim worth
  //      checking once from the learner's own connection. It is tried ONCE per
  //      video per session, so a genuinely caption-less video does not turn
  //      every retry into three more requests.
  const code = serverError?.code || "fetch_failed";
  const worthABrowserTry =
    code !== "bad_video" && code !== "video_unavailable" && code !== "aborted" &&
    (code !== "no_captions" || !browserSecondOpinionUsed.has(key));
  if (code === "no_captions") browserSecondOpinionUsed.add(key);

  if (worthABrowserTry) {
    try {
      const { data, attempts: browserAttempts } = await fetchDirectFromYouTube(id, lang || null, signal);
      attempts.push(...browserAttempts);
      data.attempts = attempts;
      rememberTranscript(key, data);
      return data;
    } catch (fallbackError) {
      if ((fallbackError as { name?: string })?.name === "AbortError") throw new TranscriptRequestError("aborted");
      if (fallbackError instanceof TranscriptRequestError) {
        attempts.push(...(fallbackError.attempts || []));
        // The browser's own answer is the more specific one when it actually
        // read the video: "empty track" beats a generic server failure.
        if (fallbackError.code === "no_transcript") {
          throw new TranscriptRequestError(fallbackError.code, fallbackError.message, attempts);
        }
      }
    }
  }

  // 3. Nothing worked. Report the server's verdict — it is the more specific
  //    one — with the whole trail attached so the page can show it.
  throw new TranscriptRequestError(
    serverError?.code || "fetch_failed",
    serverError?.message,
    attempts,
  );
}
